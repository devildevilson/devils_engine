// СБОРКА УСТРОЙСТВЕННОЙ ФОРМЫ: привязки ГЕНЕРИРУЮТСЯ, а не пишутся в тексте инструмента.
//
// Это прямое следствие §6.2 `ORIGINATOR_GPGPU.md`: «род ВЫВОДИТСЯ, форма ОБЪЯВЛЯЕТСЯ». Если род
// ресурса (буфер или картинка) выводится из того, КАК его читают во всей очереди, то инструмент не
// может знать его заранее — а значит и объявить `layout(std430 ...) buffer` в своём тексте не может.
// Пока текст писали целиком, род был спрятан в нём, и «выводится» было бы неправдой.
//
// Поэтому инструмент объявляет ТЕЛО, написанное против аксессоров, а преамбулу собирает эта функция,
// уже зная выведенные роды:
//
//   in_<i>_at(uint at)        — элемент входа (у картинки это texelFetch по свёрнутой координате);
//   in_<i>_length()           — сколько элементов во входе;
//   in_<i>_sample(vec2 uv)    — ТОЛЬКО у входа, объявленного фильтруемым: чтение МЕЖДУ элементами;
//   out_<j>_set(uint, value)  — запись своего элемента;
//   out_<j>_add(uint, value)  — атомарное накопление, только у целого буфера (см. `order_free_writes`).
//
// Второе, что этим закрывается, — ТИП. Прежние тексты объявляли `float data[]` у любого поля, а в
// очередь пускаются роды `v`, `ui` и `i`: поле `ui1`, прочитанное как `float[]`, дало бы БИТЫ,
// перевёрнутые в float, — ровно ту ошибку, которую `as_span<T>` ловит на CPU. Аксессор типизирован по
// объявленному роду поля, поэтому такого чтения больше не существует.

namespace devils_engine {
namespace originator {

// КАК вызов читает свой вход на устройстве.
//
// `filtered` — это и есть критерий §6.3: читают МЕЖДУ элементами. Ничем другим картинка от буфера не
// отличается настолько, чтобы менять род ресурса, поэтому объявляется ровно это, а «сделай картинкой»
// не объявляется вовсе.
struct device_access {
  enum values {
    plain,    // ровно свой элемент по индексу
    filtered, // выборка по нецелой координате: аппаратный фильтр между элементами
    count
  };
};

// ГДЕ поле лежит на устройстве. Величина ВЫВЕДЕННАЯ: её считает устройственный план по тому, как
// поле читают все вызовы очереди вместе, а не объявляет ни инструмент, ни автор конфига.
struct device_residence {
  enum values {
    in_buffer,
    in_image,
    count
  };
};

struct device_binding {
  field_base::values base = field_base::v;
  device_residence::values residence = device_residence::in_buffer;
  device_access::values access = device_access::plain;
  // Сколько компонент у поля. Многокомпонентное поле в раскладке `soa` лежит компонентами подряд
  // внутри элемента, поэтому оно ЧИТАЕТСЯ на устройстве тем же буфером — нужен только аксессор,
  // который берёт компоненту, а длина считается в ЭЛЕМЕНТАХ, а не в числах.
  uint32_t components = 1;
  // Выход вызова. Порядок привязок — сначала все входы, затем все выходы, тот же, что у `queue_call`.
  bool writable = false;
  // Нужен ли атомарный накопитель. Ставится только у вызова, объявившего свои записи независимыми от
  // порядка, и только у целого буфера: у плавающего сложения порядок значим (§4.3).
  bool accumulates = false;
  // Нужны ли ПЕРЕВОДЯЩИЕ перегрузки аксессоров: тело, написанное против `float`, работает и над целым
  // полем. Ставится только тем инструментам, которые объявили себя годными для любого рода
  // (`tool_description::device_integer_ready`), потому что перевод через `float32` точен лишь до
  // 2^24 — а на CPU то же поле читается через double и точно до конца диапазона.
  bool converting = false;
};

// Написание рода в GLSL: `v` -> float, `ui` -> uint, `i` -> int. Роды уже `2`/`ub`/`c` на устройство
// не переносятся вовсе и сюда не приходят.
std::string_view device_type_name(const field_base::values base) noexcept;

// ФОРМА ЧУЖОГО ТЕЛА: ТОЛЬКО ПЕРЕВОД `devils_script`, и ничто другое.
//
// Водораздел здесь не «GLSL можно или нельзя», а КТО РЕШАЕТ, ЧТО СЧИТАЕТСЯ. Устройственного кода в
// библиотеке два вида, и различаются они именно этим:
//
//   1. У НАТИВНОГО ИНСТРУМЕНТА тело написано ЗАРАНЕЕ и лежит в самой библиотеке
//      (`tool_description::device_body`). `remap`, `graph_flood`, `plate_velocity` — что именно они
//      считают, решили разработчики: это исходник проекта, он компилируется вместе с движком и
//      читается на ревью. Держать его готовым GLSL — нормально, и никакой проверки текста здесь не
//      требуется, потому что текст не приезжает ниоткуда;
//
//   2. У ЧУЖОГО ТЕЛА (`run_script`) что считается, решает АВТОР ДАННЫХ — и поэтому он приносит
//      программу `devils_script`, а НЕ шейдер. В GLSL её переводит движок, по AST, который отдаёт
//      сам `ds`. Перевод проходит проверки апертуры, привязок и отказов; принесённый готовый шейдер
//      не проходил бы ничего и получал бы прямой доступ к памяти устройства.
//
// Отсюда и этот класс. `originator.queue.run_script{...}` обязан принимать ds и только ds, поэтому
// форму чужого тела НЕЛЬЗЯ просто написать строкой: конструктор закрыт ключом, который ядро выдаёт
// ровно переводчику. Полностью закрыть дорогу без контроля над проектом невозможно — C++ обойдёт
// что угодно, — но объявление устроено так, что случайно или мимоходом это не делается.
class translated_form {
public:
  translated_form() = default;

  // Объявленный ОТКАЗ: «на устройство не переносится, и вот почему». Его вправе сказать кто угодно —
  // отказ не даёт устройству исполнить ни одной инструкции.
  static translated_form refused(std::string why);

  // Ключ на объявление формы. Конструктор закрыт, поэтому получить ключ может только тот, кому ядро
  // его выдало.
  class authority {
    authority() = default;
    friend class translation_authority;
  };

  translated_form(authority key,
                  std::string body,
                  std::vector<device_param> params,
                  std::vector<uint32_t> filtered_inputs);

  // Объявлена ли форма (есть тело). Отказ формой не считается.
  bool declared() const noexcept;
  const std::string& body() const noexcept;
  const std::vector<device_param>& params() const noexcept;
  const std::vector<uint32_t>& filtered_inputs() const noexcept;
  // Причина отказа, если она названа. Пусто и без тела — «формы просто нет».
  const std::string& refusal() const noexcept;

private:
  std::string body_;
  std::vector<device_param> params_;
  std::vector<uint32_t> filtered_inputs_;
  std::string refusal_;
};

// Собирает полный текст шейдера: шапка push-константы, привязки с аксессорами, свёртка индекса и
// тело. ОДИН способ выложить байты и один способ обратиться к полю на все инструменты и все переводы.
std::string build_device_shader(const std::span<const device_binding>& bindings,
                                const std::span<const device_param>& params,
                                const std::string_view& body,
                                const uint32_t group_size = 64);

} // namespace originator
} // namespace devils_engine

