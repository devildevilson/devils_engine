#ifndef DEVILS_ENGINE_ORIGINATOR_PRIMITIVES_H
#define DEVILS_ENGINE_ORIGINATOR_PRIMITIVES_H

#include <string_view>

#include "tools.h"

// ПРИМИТИВЫ ПОВЕРХ СТОРОННИХ БИБЛИОТЕК: FastNoise2 (поля шума) и jc_voronoi (топология областей).
// Отдельная цель сборки, потому что это внешние зависимости, а ядро генератора не обязано их тянуть;
// контракт при этом обычный — такие же инструменты с объявленной апертурой.
//
// КРОСС-МАШИННЫЙ ДЕТЕРМИНИЗМ. FastNoise2 собирает по варианту кода на каждый набор SIMD и выбирает
// его в рантайме; по умолчанию наборы расходятся (замерено 1.8e-07 между Max и SSE2). Проект
// собирает его с `FASTNOISE2_STRICT_FP` — штатной опцией upstream, после которой выход всех наборов
// ПОБИТОВО одинаков при скорости лучшего доступного. Проверено измерением. Параметр `feature_set`
// после этого диагностический: он позволяет взять конкретный набор и сравнить.
//
// РАЗМЕР ФОРМЫ ЗАДАЁТСЯ В МИРОВЫХ ЕДИНИЦАХ (`feature`) — единственный способ говорить о шуме на
// одном языке с остальным миром. Частота обратной размерности, и её перевод в метры зависит от
// МАСШТАБА ДЕРЕВА, то есть от чужих данных; предполагать его нельзя, и это уже стоило ошибки
// (частота 1/190 в расчёте на 190 метров дала форму в 17 километров, потому что период дерева
// оказался 91 единица — чанк в 32 метра видел поле постоянным, и мир вышел пустым). Поэтому масштаб
// дерева ИЗМЕРЯЕТСЯ движком: среднее расстояние между сменами знака вдоль наклонной линии, зерно
// ноль (период — свойство дерева, а не мира), результат кэшируется по тексту дерева. Дальше
// `frequency = период / feature`. Сам `frequency` остаётся для случаев, где мировая длина не имеет
// смысла (поле на единичной сфере); задать оба сразу — громкая ошибка, одно из них обязано быть
// неверным.

namespace devils_engine {
namespace originator {

// Шум: FastNoise2. Дерево узлов приходит как ЗАКОДИРОВАННАЯ СТРОКА из редактора FastNoise2, то есть
// граф шума становится данными конфига, а не кодом.
//
//   noise_grid    pointwise, 0 входов, 1 выход. Регулярная 2D-сетка: элемент i -> (i % width, i / width).
//                 params: tree (строка), width, feature ИЛИ frequency, seed_offset, x_offset,
//                         y_offset, step, amplitude, offset, feature_set (диагностический).
//   noise_at      pointwise, 1 вход (поле позиций v2 или v3), 1 выход. Выборка в произвольных точках:
//                 именно этот путь нужен кубосфере, где адрес поверхности — направление, а не (x, y).
//                 params: tree, feature ИЛИ frequency, seed_offset, amplitude, offset, feature_set.
void add_noise_tools(tool_registry& registry);

// Области: jc_voronoi и запрос ближайшего сайта.
//
//   voronoi_label      gather, 1 вход (поле позиций сайтов v2), 1 выход (метка элемента сетки).
//                      Подготовка строит kd-дерево сайтов ОДИН раз, дальше запросы независимы,
//                      поэтому проход параллелится и совпадает с последовательным.
//                      params: width, height, site_count, max_radius.
//   voronoi_polygons   scatter, 1 вход (позиции сайтов v2), 4 выхода (смещения CSR, индексы углов,
//                      уникальные вершины v2, число вершин одним элементом). Контуры областей как
//                      ПЛАНАРНАЯ СЕТКА С ОБЩИМИ вершинами: соседние области ссылаются на одну
//                      вершину, а не на две совпадающие копии, поэтому щели на стыке невозможны.
//                      params: width (обязателен), height.
//   voronoi_adjacency  scatter, 1 вход (позиции сайтов v2), 2 выхода (смещения CSR, соседи).
//                      Точная топология диаграммы: у ребра два сайта, значит соседство берётся из
//                      геометрии, а не угадывается по растру. offsets[site_count] = число дуг.
//                      params: site_count, width, height.
void add_voronoi_tools(tool_registry& registry);

void add_all_primitives(tool_registry& registry);

} // namespace originator
} // namespace devils_engine

#endif
