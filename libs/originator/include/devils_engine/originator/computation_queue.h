// ОЧЕРЕДЬ ВЫЧИСЛЕНИЙ: названная цепочка заранее объявленных вызовов, которая исполняется целиком.
// Подграф из инструментов, между которыми нет ни одного промежуточного значения в lua, существовал и
// раньше — у него просто не было имени, и потому его нельзя было ни перенести на устройство целиком,
// ни слить проходы, ни померить как одну вещь.
//
// ЧТО ЗДЕСЬ ПРИНЦИПИАЛЬНО:
//
//   ВХОДЫ ВЫВОДЯТСЯ, ВЫХОД ОБЪЯВЛЯЕТСЯ. Своих читателей внутри очередь видит сама; кто прочитает
//   результат ПОСЛЕ неё — не знает и знать не может. Это граница передачи: на устройстве то, что не
//   названо в `output`/`resident`, не обязано покидать его вовсе.
//
//   ИЗ ГРАНИЦЫ СЛЕДУЕТ ПРОВЕРКА НА МЁРТВУЮ РАБОТУ: элемент, чей выход никто не читает и который не
//   назван на границе, — потраченный проход, и об этом можно сказать до исполнения. Сюда же попадает
//   выход, перезаписанный позже без чтения.
//
//   ОДИН ОТКАЗ НА ВСЮ ОЧЕРЕДЬ, до первого вызова. Поэтому сообщение называет НОМЕР элемента, а не
//   только шаг и инструмент.
//
// В ОЧЕРЕДЬ ПУСКАЮТСЯ АПЕРТУРЫ, ПИШУЩИЕ СВОЙ ЭЛЕМЕНТ: `pointwise` и `gather`. У остальных отказов
// причины разные, и потому названы отдельно (`queue_rejection_reason`): `scatter` пишет по чужим
// индексам в ДРУГУЮ структуру и порядок его записей задаёт алгоритм — кроме вызова, объявившего
// записи независимыми от порядка; `sequential` разрывает очередь по построению; `reduce` отдаёт одно
// число, а промежуточных значений в lua у очереди нет, и ради возврата этого числа в дирижёра свёртку
// как раз и считают.
//
// Полный контекст, включая перенос на устройство, — `ORIGINATOR_GPGPU.md`.

namespace devils_engine {
namespace thread {
class atomic_pool;
}

namespace originator {

struct queue_call;

// Исполнение элемента, код которого лежит ВНЕ ядра: программа `devils_script` компилируется слоем
// `originator_script`, и ядро о ней не знает. Форма та же, что у нативного инструмента, поэтому
// очередь не различает эти два случая нигде, кроме места вызова.
using queue_body = std::function<void(const queue_call& call, const std::string_view& step_name, thread::atomic_pool* pool)>;

// Один объявленный вызов внутри очереди. Объявленный — значит собранный целиком до исполнения:
// привязки, параметры, зерно и диапазон здесь уже разрешены, и исполнение ничего не доспрашивает.
struct queue_call {
  // Имя для сообщений: инструмент или программа. Номер элемента очередь добавляет сама.
  std::string label;
  // Непусто => элемент исполняется этим телом, а не нативным инструментом (тогда tool == nullptr).
  queue_body body;
  std::vector<field_ref> inputs;
  std::vector<field_ref> outputs;
  parameters params;
  // СЧЁТЧИК: непустая ссылка означает, что число элементов читается из этого поля ПЕРЕД вызовом, а
  // `range_end` при объявлении неизвестен. Читается он именно в момент исполнения — его пишет
  // предыдущий элемент ЭТОЙ ЖЕ очереди. Ёмкость — число элементов приёмника, превышение зажимается.
  field_ref count_from{};
  const tool_description* tool = nullptr;
  uint64_t seed = 0;
  size_t range_begin = 0;
  size_t range_end = 0;
  // Апертура берётся у инструмента, а у чужого тела — у того, кто его собрал. Скрипт её не выбирает.
  aperture::values shape = aperture::pointwise;

  // ФОРМА ЧУЖОГО ТЕЛА НА УСТРОЙСТВЕ — ТОЛЬКО ПЕРЕВОД `devils_script` (см. `device_form.h`). Ядро
  // очереди не узнаёт ни про GLSL, ни про транслятор — оно переносит объявление дальше. Объявленный
  // ОТКАЗ вправе сказать кто угодно: очередь на CPU от него не страдает, а устройственный план
  // отказывает С ПРИЧИНОЙ, а не молча.
  translated_form device;

  // Записи вызова не зависят от порядка — то же объявление, что у `tool_description`, и по той же
  // причине. У нативного инструмента берётся у него.
  bool order_free_writes = false;

  size_t range_count() const noexcept;
  // Читается ли число элементов из поля, а не задано числом.
  bool indirect() const noexcept;
  // Один и тот же (буфер, поле) среди входов и среди выходов. Нужно и проверке мёртвой работы, и
  // группировке слияния, и выводу барьеров: все три спрашивают, читает ли следующий проход то, что
  // записал предыдущий. СЧЁТЧИК тоже считается чтением — проход, посчитавший длину, живой именно
  // потому, что её читает следующий.
  bool reads(const field_ref& field) const noexcept;
  bool writes(const field_ref& field) const noexcept;
};

struct computation_queue {
  // Обычно имя шага: очередь живёт внутри шага, и сообщения обязаны называть его.
  std::string name;
  std::vector<queue_call> calls;
  // ГРАНИЦА ПЕРЕДАЧИ: что уезжает НА ХОСТ.
  std::vector<field_ref> output;
  // ГРАНИЦА ЖИЗНИ БЕЗ ПЕРЕДАЧИ: поле живое, но на хост не едет — так остаётся на устройстве видимая
  // текстура, которую читает пост-процесс, очереди не видный. Пока список был один, у него было два
  // смысла сразу: назвать такое поле в `output` значило скачать мегабайт ради того, чтобы проход не
  // сочли мёртвым, а не назвать — получить отказ на честной работе. Проверке мёртвой работы оба
  // списка равны, различаются они только планом передачи; на пути CPU разницы нет вовсе.
  std::vector<field_ref> resident;

  // ГДЕ ОЧЕРЕДЬ СЧИТАЕТСЯ — ОБЪЯВЛЕНИЕ, а не догадка. Выбор пути не имеет права быть свойством
  // МАШИНЫ: молча посчитав на CPU очередь, решённую на GPU, генератор выдал бы другой мир под тем же
  // зерном. Поэтому решение живёт в конфиге, а машина, которая его исполнить не может, отказывает
  // ГРОМКО. По умолчанию CPU: путь на CPU обязателен всегда, устройство запрашивается.
  bool on_device = false;
};


// Результат проверки очереди. Пустое сообщение => очередь допустима.
struct queue_check {
  bool allowed = true;
  std::string message;
};

// Пускается ли апертура в очередь САМА ПО СЕБЕ. У `scatter` есть объявляемое исключение
// (`order_free_writes`), и знает о нём проверка очереди, а не апертура: свойство принадлежит
// инструменту, а не роду адресации.
bool fits_in_queue(const aperture::values value) noexcept;

// Почему именно ЭТА апертура не пускается: у трёх отказов три разные причины, и автор обязан узнать
// свою. Текст живёт рядом с правилом, поэтому он один и тот же у всех, кто отклоняет вызов.
std::string_view queue_rejection_reason(const aperture::values value) noexcept;

// Проверяет очередь целиком, не исполняя её: апертуры, привязки каждого элемента (нативный
// инструмент — тем же `check_dispatch`, что и одиночный вызов), объявленный выход и мёртвую работу.
queue_check check_queue(const computation_queue& queue);

// СЛИЯНИЕ ПРОХОДОВ — единственный источник настоящего ускорения на CPU: два подряд `pointwise`
// вызова над одним диапазоном выполняются в ОДНОМ обходе данных, и промежуточное поле остаётся в
// кэше вместо круга через память. Механизм — перестановка обхода: вместо «вызов, потом его чанки»
// очередь идёт «плитка, потом все вызовы группы».
//
// Законно это ровно для `pointwise` и ровно при равных диапазонах: элемент i второго вызова читает
// ТОЛЬКО элемент i, а его в этой же плитке уже записал первый. У `gather` ломается — ему нужен весь
// предыдущий проход; при разных диапазонах ломается тоже, потому что плитка одного не является
// плиткой другого. Побитовое равенство сохраняется по той же причине, что и у одиночного вызова:
// результат элемента зависит только от его входов и зерна. Это проверяется тестом.
//
// РАЗМЕР ПЛИТКИ выводится из рабочего набора группы: сумма байт на элемент по РАЗЛИЧНЫМ полям. Целевой
// объём взят как размер L1d и является НАЧАЛЬНЫМ значением для замера, а не выведенной величиной.
constexpr size_t fusion_tile_bytes = 32 * 1024;
// Ниже этого плитка не опускается: за плитку платится вход в тело каждого вызова группы.
constexpr size_t minimum_fusion_tile = 256;

// Что стоило исполнение. `passes` — число РЕАЛЬНЫХ обходов данных (слитая группа из трёх вызовов это
// один обход), `fused` — сколько вызовов в такие группы попало: выигрыш от слияния обязан быть
// ИЗМЕРЕН, а не предположен.
struct queue_report {
  size_t calls = 0;
  size_t passes = 0;
  size_t fused = 0;
  // Сколько вызовов упёрлось в ёмкость приёмника: счётчик просил больше элементов, чем объявлено.
  // ХОСТ ОБЯЗАН ЭТО ЧИТАТЬ: отказать нельзя (на устройстве бросить нечем, а два поведения у одного
  // объявления недопустимы), но тихо обрезанный проход не отследить по результату.
  size_t clamped = 0;
  // Считалась ли очередь НА УСТРОЙСТВЕ: путь объявлен в конфиге, но подтверждение того, что он и был
  // взят, приходит только отсюда.
  bool on_device = false;
};

// ИСПОЛНИТЕЛЬ ОЧЕРЕДИ, ОБЪЯВИВШЕЙ СЕБЯ УСТРОЙСТВЕННОЙ. Ядро очереди про Vulkan не знает — иначе цель
// `originator` потянула бы за собой painter. Реализацию даёт `devils_engine::originator_device`, а
// ставит её тот, кто собрал приложение. Отсутствие исполнителя у очереди с `on_device` — громкий
// отказ, а не тихий переход на CPU.
class queue_executor {
public:
  virtual ~queue_executor() = default;

  // Можно ли исполнить. Пустое сообщение => можно. Отказ здесь — законный ответ, по которому
  // вызывающий обязан упасть, а не подставить другой путь.
  virtual bool can_run(const computation_queue& queue, std::string& refusal) = 0;
  virtual queue_report run(const computation_queue& queue) = 0;
};

// Исполняет очередь по порядку. Недопустимая очередь — критическая ошибка конфига/скрипта:
// бросает utils::error с именем шага и номером элемента, не начав работу.
queue_report run_queue(const computation_queue& queue, thread::atomic_pool* pool);

} // namespace originator
} // namespace devils_engine

#endif
