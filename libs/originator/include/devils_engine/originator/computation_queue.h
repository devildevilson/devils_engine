#ifndef DEVILS_ENGINE_ORIGINATOR_COMPUTATION_QUEUE_H
#define DEVILS_ENGINE_ORIGINATOR_COMPUTATION_QUEUE_H

#include <cstddef>
#include <cstdint>
#include <functional>
#include <string>
#include <string_view>
#include <vector>

#include "common.h"
#include "tools.h"

// Очередь вычислений: НАЗВАННАЯ цепочка заранее объявленных вызовов, которая исполняется целиком.
//
// Понятие взято не из головы, а из уже написанного кода: в телах шагов встречаются цепочки
// инструментов, между которыми нет ни одного промежуточного значения в lua (`box_blur` -> `classify`
// в GN01 — ровно такая). Значит подграф уже существует — у него просто нет имени, и потому его
// нельзя ни перенести целиком, ни слить проходы, ни померить как одну вещь. Очередь даёт ему имя.
//
// Что здесь принципиально:
//
//   ВХОДЫ ВЫВОДЯТСЯ, ВЫХОД ОБЪЯВЛЯЕТСЯ. Всех своих читателей внутри очередь видит сама: поле,
//   которое читает элемент и не писал ни один элемент до него, — это вход, и вычислить его список
//   можно. А кто прочитает результат ПОСЛЕ очереди, очередь не знает и знать не может, поэтому
//   `output` называется вслух. Это не удобство, а граница передачи: на устройстве то, что не названо
//   в `output`, не обязано покидать его вовсе, а что названо — обязано.
//
//   ИЗ ГРАНИЦЫ СЛЕДУЕТ ПРОВЕРКА НА МЁРТВУЮ РАБОТУ. Элемент, чей выход никто дальше не читает, а сам
//   он в `output` не назван, — мёртвый, и об этом можно сказать вслух до исполнения, ровно как
//   сейчас говорится про непривязанный буфер. Сюда же попадает выход, ПЕРЕЗАПИСАННЫЙ позже без
//   чтения: посчитанное поле, которое следующий элемент затирает, — это потраченный проход.
//
//   ОДИН ОТКАЗ НА ВСЮ ОЧЕРЕДЬ. Очередь проверяется до первого вызова, а не падает на середине
//   работы. Поэтому сообщение называет номер элемента в очереди, а не только шаг и инструмент.
//
// Апертуры, которые в очередь пускаются, — ровно те, что пишут СВОЙ элемент в объявленный выход:
// `pointwise` и `gather`. Остальные отклоняются, и у каждого отказа своя причина, а не общая:
//
//   scatter     пишет по чужим индексам, и его выход это ДРУГАЯ структура; порядок задаёт алгоритм,
//               а не очередь, поэтому такой инструмент вызывается сам по себе;
//   sequential  порядок значим по построению — очередь на нём разрывается, и это граница, видимая
//               в конфиге;
//   reduce      отдаёт ОДНО число, а у очереди нет промежуточных значений в lua — деть его некуда.
//               Свёртку и считают ради того, чтобы прочитать её результат и параметризовать
//               следующий вызов (так работает нормализация в GN01), то есть ради того самого
//               возврата в дирижёра, которого очередь и не делает.
//
// Полный контекст, включая перенос на устройство, — `ORIGINATOR_GPGPU.md`.

namespace devils_engine {
namespace thread {
class atomic_pool;
}

namespace originator {

struct queue_call;

// Исполнение элемента, код которого лежит ВНЕ ядра: программа `devils_script` компилируется слоем
// `originator_script`, и ядро о ней не знает. Форма та же, что у нативного инструмента, поэтому
// очередь не различает эти два случая нигде, кроме места вызова.
using queue_body = std::function<void(const queue_call& call, const std::string_view& step_name, thread::atomic_pool* pool)>;

// Один объявленный вызов внутри очереди. Объявленный — значит собранный целиком до исполнения:
// привязки, параметры, зерно и диапазон здесь уже разрешены, и исполнение ничего не доспрашивает.
struct queue_call {
  // Имя для сообщений: инструмент или программа. Номер элемента очередь добавляет сама.
  std::string label;
  // Непусто => элемент исполняется этим телом, а не нативным инструментом (тогда tool == nullptr).
  queue_body body;
  std::vector<field_ref> inputs;
  std::vector<field_ref> outputs;
  parameters params;
  const tool_description* tool = nullptr;
  uint64_t seed = 0;
  size_t range_begin = 0;
  size_t range_end = 0;
  // Апертура берётся у инструмента, а у чужого тела — у того, кто его собрал. Скрипт её не выбирает.
  aperture::values shape = aperture::pointwise;
};

struct computation_queue {
  // Обычно имя шага: очередь живёт внутри шага, и сообщения обязаны называть его.
  std::string name;
  std::vector<queue_call> calls;
  // ГРАНИЦА ПЕРЕДАЧИ, объявленная автором. Пустой список — отказ: очередь, ничего не отдающая
  // наружу, не сделала ничего наблюдаемого.
  std::vector<field_ref> output;
};

// Результат проверки очереди. Пустое сообщение => очередь допустима.
struct queue_check {
  bool allowed = true;
  std::string message;
};

// Пускается ли апертура в очередь. Причины отказа — в комментарии к файлу.
bool fits_in_queue(const aperture::values value) noexcept;

// Почему именно ЭТА апертура не пускается. Общего «не подходит» здесь недостаточно: у трёх отказов
// три разные причины, и автор обязан узнать свою, а не догадываться. Текст живёт рядом с правилом,
// поэтому он один и тот же и у проверки очереди, и у того, кто отклоняет вызов раньше — на записи.
std::string_view queue_rejection_reason(const aperture::values value) noexcept;

// Проверяет очередь целиком, не исполняя её: апертуры, привязки каждого элемента (нативный
// инструмент — тем же `check_dispatch`, что и одиночный вызов), объявленный выход и мёртвую работу.
queue_check check_queue(const computation_queue& queue);

// Что стоило исполнение. `passes` — число реальных обходов данных; сегодня оно равно числу
// элементов, а слияние соседних `pointwise` (следующий срез) обязано его уменьшить. Величина
// существует именно затем, чтобы выигрыш от слияния был ИЗМЕРЕН, а не предположен.
struct queue_report {
  size_t calls = 0;
  size_t passes = 0;
};

// Исполняет очередь по порядку. Недопустимая очередь — критическая ошибка конфига/скрипта:
// бросает utils::error с именем шага и номером элемента, не начав работу.
queue_report run_queue(const computation_queue& queue, thread::atomic_pool* pool);

} // namespace originator
} // namespace devils_engine

#endif
