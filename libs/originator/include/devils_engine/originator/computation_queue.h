// Очередь вычислений: НАЗВАННАЯ цепочка заранее объявленных вызовов, которая исполняется целиком.
//
// Понятие взято не из головы, а из уже написанного кода: в телах шагов встречаются цепочки
// инструментов, между которыми нет ни одного промежуточного значения в lua (`box_blur` -> `classify`
// в GN01 — ровно такая). Значит подграф уже существует — у него просто нет имени, и потому его
// нельзя ни перенести целиком, ни слить проходы, ни померить как одну вещь. Очередь даёт ему имя.
//
// Что здесь принципиально:
//
//   ВХОДЫ ВЫВОДЯТСЯ, ВЫХОД ОБЪЯВЛЯЕТСЯ. Всех своих читателей внутри очередь видит сама: поле,
//   которое читает элемент и не писал ни один элемент до него, — это вход, и вычислить его список
//   можно. А кто прочитает результат ПОСЛЕ очереди, очередь не знает и знать не может, поэтому
//   `output` называется вслух. Это не удобство, а граница передачи: на устройстве то, что не названо
//   в `output`, не обязано покидать его вовсе, а что названо — обязано.
//
//   ИЗ ГРАНИЦЫ СЛЕДУЕТ ПРОВЕРКА НА МЁРТВУЮ РАБОТУ. Элемент, чей выход никто дальше не читает, а сам
//   он в `output` не назван, — мёртвый, и об этом можно сказать вслух до исполнения, ровно как
//   сейчас говорится про непривязанный буфер. Сюда же попадает выход, ПЕРЕЗАПИСАННЫЙ позже без
//   чтения: посчитанное поле, которое следующий элемент затирает, — это потраченный проход.
//
//   ОДИН ОТКАЗ НА ВСЮ ОЧЕРЕДЬ. Очередь проверяется до первого вызова, а не падает на середине
//   работы. Поэтому сообщение называет номер элемента в очереди, а не только шаг и инструмент.
//
// Апертуры, которые в очередь пускаются, — ровно те, что пишут СВОЙ элемент в объявленный выход:
// `pointwise` и `gather`. Остальные отклоняются, и у каждого отказа своя причина, а не общая:
//
//   scatter     пишет по чужим индексам, и его выход это ДРУГАЯ структура; порядок этих записей
//               задаёт алгоритм, а не очередь, поэтому такой инструмент вызывается сам по себе.
//               ИСКЛЮЧЕНИЕ ровно одно и оно объявляется вслух: вызов, чьи записи НЕ ЗАВИСЯТ ОТ
//               ПОРЯДКА (`order_free_writes`), в очередь пускается — потому что отклоняли не чужие
//               индексы, а порядок, а у целочисленного накопления порядка нет вовсе;
//   sequential  порядок значим по построению — очередь на нём разрывается, и это граница, видимая
//               в конфиге;
//   reduce      отдаёт ОДНО число, а у очереди нет промежуточных значений в lua — деть его некуда.
//               Свёртку и считают ради того, чтобы прочитать её результат и параметризовать
//               следующий вызов (так работает нормализация в GN01), то есть ради того самого
//               возврата в дирижёра, которого очередь и не делает.
//
// Полный контекст, включая перенос на устройство, — `ORIGINATOR_GPGPU.md`.

namespace devils_engine {
namespace thread {
class atomic_pool;
}

namespace originator {

struct queue_call;

// Исполнение элемента, код которого лежит ВНЕ ядра: программа `devils_script` компилируется слоем
// `originator_script`, и ядро о ней не знает. Форма та же, что у нативного инструмента, поэтому
// очередь не различает эти два случая нигде, кроме места вызова.
using queue_body = std::function<void(const queue_call& call, const std::string_view& step_name, thread::atomic_pool* pool)>;

// Один объявленный вызов внутри очереди. Объявленный — значит собранный целиком до исполнения:
// привязки, параметры, зерно и диапазон здесь уже разрешены, и исполнение ничего не доспрашивает.
struct queue_call {
  // Имя для сообщений: инструмент или программа. Номер элемента очередь добавляет сама.
  std::string label;
  // Непусто => элемент исполняется этим телом, а не нативным инструментом (тогда tool == nullptr).
  queue_body body;
  std::vector<field_ref> inputs;
  std::vector<field_ref> outputs;
  parameters params;
  // СЧЁТЧИК: непустая ссылка означает, что число элементов читается из этого поля ПЕРЕД вызовом, а
  // `range_end` при объявлении неизвестен. Читается счётчик именно в момент исполнения — его пишет
  // предыдущий элемент ЭТОЙ ЖЕ очереди, и прочитанное при объявлении было бы значением с прошлого
  // раза. Ёмкостью служит число элементов приёмника, и превышение зажимается по ней.
  field_ref count_from{};
  const tool_description* tool = nullptr;
  uint64_t seed = 0;
  size_t range_begin = 0;
  size_t range_end = 0;
  // Апертура берётся у инструмента, а у чужого тела — у того, кто его собрал. Скрипт её не выбирает.
  aperture::values shape = aperture::pointwise;

  // ФОРМА ЧУЖОГО ТЕЛА НА УСТРОЙСТВЕ. У нативного инструмента она объявлена самим инструментом
  // (`tool_description::device_body`), а сюда её кладёт тот, кто собрал чужое тело: для программы
  // `devils_script` это перевод в GLSL. Ядро очереди при этом не узнаёт ни про GLSL, ни про
  // транслятор — оно только переносит объявление дальше.
  //
  // Пусто вместе с непустым `device_refusal` означает «на устройство не переносится, и вот почему»:
  // очередь на CPU от этого не страдает, а устройственный план отказывает С ПРИЧИНОЙ, а не молча.
  //
  // Тело пишется против аксессоров, а не против `layout(...) buffer`: привязки собирает
  // `build_device_shader`, потому что род поля (буфер или картинка) ВЫВОДИТСЯ из всей очереди и
  // одному вызову не известен. В отличие от нативного инструмента, чужое тело писали ПОД ЭТИ поля,
  // поэтому ему достаются аксессоры объявленного рода (`uint`, `int`), а не только плавающие.
  std::string device_body;
  std::vector<device_param> device_params;
  std::vector<uint32_t> device_filtered_inputs;
  std::string device_refusal;

  // Записи вызова не зависят от порядка — то же объявление, что у `tool_description`, и по той же
  // причине: `scatter` отклоняется за порядок записей, а не за чужие индексы, и целочисленное
  // накопление — тот случай, где порядка нет вовсе. У нативного инструмента берётся у него.
  bool order_free_writes = false;

  size_t range_count() const noexcept;
  // Читается ли число элементов из поля, а не задано числом.
  bool indirect() const noexcept;
  // Один и тот же (буфер, поле) среди входов и среди выходов. Нужно и проверке мёртвой работы, и
  // группировке слияния: обе спрашивают, читает ли следующий проход то, что записал предыдущий.
  //
  // СЧЁТЧИК тоже считается чтением, и это не мелочь: проход, посчитавший длину, живой именно потому,
  // что её читает следующий, а барьер между ними выводится тем же вопросом.
  bool reads(const field_ref& field) const noexcept;
  bool writes(const field_ref& field) const noexcept;
};

struct computation_queue {
  // Обычно имя шага: очередь живёт внутри шага, и сообщения обязаны называть его.
  std::string name;
  std::vector<queue_call> calls;
  // ГРАНИЦА ПЕРЕДАЧИ, объявленная автором: что уезжает НА ХОСТ. На устройстве то, что здесь не
  // названо, не обязано покидать его вовсе; что названо — обязано.
  std::vector<field_ref> output;

  // ГРАНИЦА ЖИЗНИ БЕЗ ПЕРЕДАЧИ: поле живое, но на хост НЕ едет.
  //
  // Разделение появилось из первого же настоящего потребителя (GN04): видимая текстура остаётся на
  // устройстве и читается ПОТОМ — пост-процессом, который очередь не видит, ровно как не видит и
  // читателя из `output`. Пока список был один, у него было два смысла сразу — «живо» и «едет», — и
  // для такого поля они расходятся: назвать его в `output` значило скачать мегабайт ради того, чтобы
  // проход не сочли мёртвым, а не назвать — получить отказ на честной работе.
  //
  // Проверке мёртвой работы оба списка равны: она спрашивает «прочитает ли это хоть кто-нибудь», а не
  // «где живёт читатель». Различаются они только планом передачи, и в этом весь смысл.
  //
  // На пути CPU разницы нет вовсе: там всё и так лежит в памяти хоста, и `resident` означает просто
  // «живо».
  std::vector<field_ref> resident;
};

// Результат проверки очереди. Пустое сообщение => очередь допустима.
struct queue_check {
  bool allowed = true;
  std::string message;
};

// Пускается ли апертура в очередь САМА ПО СЕБЕ. Причины отказа — в комментарии к файлу; у `scatter`
// есть объявляемое исключение (`order_free_writes`), и знает о нём проверка очереди, а не апертура:
// свойство принадлежит инструменту, а не роду адресации.
bool fits_in_queue(const aperture::values value) noexcept;

// Почему именно ЭТА апертура не пускается. Общего «не подходит» здесь недостаточно: у трёх отказов
// три разные причины, и автор обязан узнать свою, а не догадываться. Текст живёт рядом с правилом,
// поэтому он один и тот же и у проверки очереди, и у того, кто отклоняет вызов раньше — на записи.
std::string_view queue_rejection_reason(const aperture::values value) noexcept;

// Проверяет очередь целиком, не исполняя её: апертуры, привязки каждого элемента (нативный
// инструмент — тем же `check_dispatch`, что и одиночный вызов), объявленный выход и мёртвую работу.
queue_check check_queue(const computation_queue& queue);

// СЛИЯНИЕ ПРОХОДОВ. Единственный источник настоящего ускорения на CPU: два подряд `pointwise`
// вызова над одним диапазоном можно выполнить в ОДНОМ обходе данных, и промежуточное поле останется
// в кэше вместо круга через память.
//
// Механизм — перестановка обхода: вместо «вызов, потом его чанки» очередь идёт «плитка, потом все
// вызовы группы». Законно это ровно для `pointwise` и ровно при равных диапазонах: элемент i второго
// вызова читает ТОЛЬКО элемент i, а его в этой же плитке уже записал первый вызов. У `gather` это
// ломается — ему нужны соседи, то есть весь предыдущий проход целиком; у разных диапазонов ломается
// тоже, потому что плитка одного не является плиткой другого.
//
// Побитовое равенство при этом сохраняется по той же причине, по которой оно есть у одиночного
// pointwise-вызова: результат элемента зависит только от его собственных входов и от зерна, а не от
// того, как работа разложилась по плиткам и потокам. Это проверяется тестом, а не предполагается.
//
// РАЗМЕР ПЛИТКИ выводится из рабочего набора группы: сумма байт на элемент по РАЗЛИЧНЫМ полям (то же
// поле, которое один вызов пишет, а следующий читает, считается один раз — оно и есть то, что
// слияние оставляет в кэше). Целевой объём взят как размер L1d и является НАЧАЛЬНЫМ значением для
// замера, а не выведенной величиной: правильное число говорит замер на настоящих размерах.
constexpr size_t fusion_tile_bytes = 32 * 1024;
// Ниже этого плитка не опускается: за плитку платится вход в тело каждого вызова группы, и на совсем
// маленькой плитке эта плата съедает выигрыш от кэша.
constexpr size_t minimum_fusion_tile = 256;

// Что стоило исполнение.
//
// `passes` — число РЕАЛЬНЫХ обходов данных: слитая группа из трёх вызовов это один обход. Величина
// существует именно затем, чтобы выигрыш от слияния был ИЗМЕРЕН, а не предположен; `fused` говорит,
// сколько вызовов в такие группы попало, то есть сколько работы слияние вообще коснулось.
struct queue_report {
  size_t calls = 0;
  size_t passes = 0;
  size_t fused = 0;
  // Сколько вызовов упёрлось в ёмкость приёмника: счётчик просил больше элементов, чем объявлено.
  // ХОСТ ОБЯЗАН ЭТО ЧИТАТЬ. Отказать нельзя — на устройстве бросить нечем, а значит и здесь нельзя,
  // иначе у одного объявления два поведения; но тихо обрезанный проход не отследить по результату,
  // поэтому факт возвращается наружу и виден телу шага.
  size_t clamped = 0;
};

// Исполняет очередь по порядку. Недопустимая очередь — критическая ошибка конфига/скрипта:
// бросает utils::error с именем шага и номером элемента, не начав работу.
queue_report run_queue(const computation_queue& queue, thread::atomic_pool* pool);

} // namespace originator
} // namespace devils_engine

#endif
