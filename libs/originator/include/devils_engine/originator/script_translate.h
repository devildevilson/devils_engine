// ПЕРЕВОД программы `devils_script` в GLSL вычислительного шейдера.
//
// ИДЁТ ОН ПО AST, КОТОРЫЙ ОТДАЁТ САМ `ds` (`make_script_ast`), а не по второму разбору текста. У ds
// уже есть парсер, у него уже зарегистрированы операторы со своими приоритетами и фиксностью, и
// второй набор правил разошёлся бы с первым МОЛЧА — то есть два пути считали бы разное, ровно то,
// чего перевод и должен избежать. Транслятор — второй ПОТРЕБИТЕЛЬ одного разбора, а не второй разбор.
//
// ПРОВЕРКУ ТИПОВ ДЕЛАЕТ glslc — тоже решение, а не лень: свой вывод типов был бы третьей системой
// типов в проекте (после ds и Vulkan) и разъехался бы с обеими. Шейдер, который не компилируется, —
// отказ с сообщением компилятора. Непереводимая конструкция — тоже ОТКАЗ, с её именем и позицией в
// тексте: молча выпущенный шейдер, который считает не то, был бы худшим из исходов.
//
// АРИФМЕТИКА ПЕРЕВОДИТСЯ ВО FLOAT32 (ds считает в double), и побитового совпадения путей генератору
// не нужно (§4.2 `ORIGINATOR_GPGPU.md`). Целочисленная программа на небольших числах совпадает
// ТОЧНО — float32 представляет целые до 2^24 без потерь, — и поэтому первый тест транслятора обязан
// быть целочисленным: только на нём сверка двух путей осмысленна.
//
// ЧТО ПЕРЕВОДИТСЯ: математика ds (имена совпадают с GLSL), `value_or`, `inv`, ветвления `select`,
// `sequence`, `switch`, `random`, случайность `chance`/`rndmix`/`rndmix1` и локали `ctx_save` /
// `ctx_set`. Равенство переводится СРАВНЕНИЕМ С ДОПУСКОМ, как его и считает ds. Не переводятся
// списки (нужна динамическая память на элемент), диагностика (`assert`, `trace`) и `execute` (нужны
// своя трансляция и свой фрейм) — у каждого отказа своя причина, и она называется вслух.
//
// ГДЕ ДВА ПУТИ РАСХОДЯТСЯ НАМЕРЕННО, и это надо знать до того, как результат покажется странным:
//
//   СЛУЧАЙНОСТЬ. У ds соль каждого места вызова генерирует ЭМИТТЕР при компиляции (`gen_value()`), и
//   в AST её нет вовсе, а состояние PRNG 64-битное. Устройство берёт зерно вызова из общей шапки
//   push-константы, соль — из порядка обхода перевода, а хеш — 32-битный `utils::shared::prng2`.
//   Значит `chance` на устройстве это СВОЙ поток: тот же элемент, то же зерно, повторяемо прогон в
//   прогон и независимо от разбиения работы, но НЕ то же число, что на CPU. Очередь, объявившая
//   `device = true`, обязана считаться устройством всегда — иначе мир менялся бы от машины;
//
//   `switch` БЕЗ СОВПАВШЕЙ ВЕТКИ отдаёт ноль. У ds ветки по умолчанию нет вовсе и такой `switch` не
//   кладёт значения на стек; ноль здесь — определённое поведение вместо неопределённого;
//
//   `ctx_save` И `ctx_set` — ЛОКАЛИ ШЕЙДЕРА, объявленные ДО записи результата. Поэтому запись
//   изнутри ветки отклоняется: локаль вычисляется до того, как ветка выбрана, и запись состоялась бы
//   и тогда, когда ветка не выбрана. Доказательства доминирования у перевода нет, и граница
//   проведена по синтаксису, а не по догадке.

namespace devils_engine {
namespace originator {

// Что транслятор знает о привязке: имя, под которым поле видно в скрипте, и род его хранения. Род
// нужен потому, что буфер шейдера ТИПИЗИРОВАН. В очередь пускаются 32-битные роды (`v`, `ui`, `i`),
// у остальных на устройстве нет представления без расширений.
struct translated_field {
  std::string name;
  field_base::values base = field_base::v;
};

struct translation {
  // Готовый текст шейдера, собранный ОБЩИМ сборщиком (`build_device_shader`). Отдаётся ради отладки
  // и тестов: в устройственную очередь кладут `body` и `params`, потому что род поля выводится из
  // ВСЕЙ очереди, и собирать текст обязан тот, кто её видит целиком.
  std::string source;
  // ОБЪЯВЛЕННАЯ ФОРМА: то, что кладут в `queue_call::device`. Собрать её из строки нельзя — она
  // выдаётся только здесь, и это единственный способ для чужого тела попасть на устройство.
  translated_form form;
  std::vector<std::string> arguments;
  // Размер рабочей группы, объявленный в тексте. Отдаётся наружу потому, что диспатч обязан считать
  // число групп по НЕМУ, а не по своему представлению о нём.
  uint32_t group_size = 64;
};

// ДЕРЖАТЕЛЬ КЛЮЧА на объявление устройственной формы. Существует затем, чтобы «форму выдал перевод»
// было утверждением КОМПИЛЯТОРА, а не комментарием.
class translation_authority {
public:
  static translated_form::authority key() noexcept { return translated_form::authority{}; }
};

// Переводит текст программы против имён и родов привязок — тех же имён и в том же порядке, что у
// `script_program::compile`.
translation translate_to_glsl(const std::string_view& name,
                             const std::string_view& source,
                             const std::span<const translated_field>& inputs,
                             const translated_field& output,
                             const script_program::result_kind kind,
                             const uint32_t group_size = 64);

} // namespace originator
} // namespace devils_engine

#endif
