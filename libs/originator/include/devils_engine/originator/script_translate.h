// ПЕРЕВОД программы `devils_script` в GLSL вычислительного шейдера.
//
// Идёт он по AST, который отдаёт САМ `devils_script` (`make_script_ast`), а не по второму разбору
// текста. Это главное решение здесь: у ds уже есть парсер (tavl плюс его адаптер), у него уже
// зарегистрированы операторы со своими приоритетами и фиксностью, и второй набор правил разошёлся бы
// с первым МОЛЧА — а расхождение здесь означает, что два пути считают разное, то есть ровно то, чего
// перевод и должен избежать. Поэтому транслятор — второй ПОТРЕБИТЕЛЬ одного разбора, а не второй
// разбор.
//
// Проверку типов делает glslc. Это тоже решение, а не лень: свой вывод типов означал бы третью
// систему типов в проекте (после ds и Vulkan), и она разъехалась бы с обеими. Шейдер, который не
// компилируется, — отказ с сообщением компилятора.
//
// Арифметика переводится во float32: `ds` считает в double, и побитового совпадения двух путей
// генератору не нужно (§4.2 в `ORIGINATOR_GPGPU.md`). Целочисленная программа на небольших числах
// при этом совпадает ТОЧНО — float32 представляет целые до 2^24 без потерь, — и именно поэтому
// первый тест транслятора обязан быть целочисленным: только на нём сверка двух путей осмысленна.
//
// Случайность (`chance`, `random`, `rndmix`) пока НЕ переводится, и причина не в ширине хеша, как
// предполагал §3.1. Соль каждого места вызова генерирует эмиттер ds при компиляции
// (`ctx->gen_value()`), и в AST её нет вовсе: перевести случайность можно, только прочитав
// скомпилированный контейнер либо получив соль от ds. 32-битный PRNG для этого уже есть и уже общий
// для C++ и GLSL — `utils::shared::prng2`/`prng_normalize`.

namespace devils_engine {
namespace originator {

// Что транслятор знает о привязке: имя, под которым поле видно в скрипте, и род его хранения.
//
// Род нужен потому, что буфер шейдера ТИПИЗИРОВАН: `float[]` над сырым `uint32` читал бы биты float
// — та же ошибка, которую `as_span<T>` ловит на CPU. В очередь пускаются 32-битные роды (`v`, `ui`,
// `i`), у остальных на устройстве нет представления без расширений (§3.2).
struct translated_field {
  std::string name;
  field_base::values base = field_base::v;
};

struct translation {
  // Готовый текст шейдера, собранный ОБЩИМ сборщиком (`build_device_shader`): входы на биндингах
  // 0..n-1 в порядке привязок, выход — биндинг n, push-константа с общей шапкой
  // (`count, begin, extent_x, extent_y`) и объявленными аргументами за ней.
  //
  // Отдаётся ради отладки и тестов. В устройственную очередь кладут `body` и `params`: род поля
  // (буфер или картинка) выводится из ВСЕЙ очереди, поэтому собирать текст обязан тот, кто её видит
  // целиком, а не перевод одной программы.
  std::string source;
  // ОБЪЯВЛЕННАЯ ФОРМА: то, что кладут в `queue_call::device`. Собрать её из строки нельзя — она
  // выдаётся только здесь, и это единственный способ для чужого тела попасть на устройство.
  translated_form form;
  std::vector<std::string> arguments;
  // Размер рабочей группы, объявленный в тексте. Отдаётся наружу потому, что диспатч обязан считать
  // число групп по НЕМУ, а не по своему представлению о нём.
  uint32_t group_size = 64;
};

// Переводит текст программы против имён и родов привязок — тех же имён и в том же порядке, что у
// `script_program::compile`. Непереводимая конструкция это ОТКАЗ с её именем и позицией в тексте:
// молча выпущенный шейдер, который считает не то, был бы худшим из возможных исходов.
// ДЕРЖАТЕЛЬ КЛЮЧА на объявление устройственной формы. Существует затем, чтобы «форму выдал перевод»
// было утверждением КОМПИЛЯТОРА, а не комментарием: конструктор `translated_form::authority` закрыт,
// и получить его может только этот класс.
class translation_authority {
public:
  static translated_form::authority key() noexcept { return translated_form::authority{}; }
};

translation translate_to_glsl(const std::string_view& name,
                             const std::string_view& source,
                             const std::span<const translated_field>& inputs,
                             const translated_field& output,
                             const script_program::result_kind kind,
                             const uint32_t group_size = 64);

} // namespace originator
} // namespace devils_engine

#endif
