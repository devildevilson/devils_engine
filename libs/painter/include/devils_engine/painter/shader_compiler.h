#ifndef DEVILS_ENGINE_PAINTER_SHADER_COMPILER_H
#define DEVILS_ENGINE_PAINTER_SHADER_COMPILER_H

#include <cstddef>
#include <cstdint>
#include <memory>
#include <string>
#include <vector>

// ПЕРЕИСПОЛЬЗУЕМЫЙ КОМПИЛЯТОР GLSL, КОТОРЫЙ ПЕРЕДАЮТ СНАРУЖИ.
//
// Существует потому, что конструктор `shaderc::Compiler` поднимает внутреннее состояние glslang и
// стоит около 90 мс — независимо от того, что компилируется. Пока компилятор создавался внутри
// компиляции, эту цену платил КАЖДЫЙ шейдер движка: 98% времени компиляции уходило на то, чтобы
// завести компилятор и тут же его выбросить.
//
// ПОЧЕМУ ОБЪЕКТ, А НЕ `thread_local`. Скрытое состояние на поток отвечает на вопрос «сколько их»
// молча и не даёт ответить на вопрос «когда он умирает»: у процесса, который компилирует шейдеры
// один раз при старте, состояние glslang остаётся жить до конца. Здесь владение НАЗВАНО — компилятор
// создаёт тот, кто компилирует ПАЧКУ, и держит ровно столько, сколько нужно.
//
// НЕ ПОТОКОБЕЗОПАСЕН: один объект — один поток компиляции. Двум потокам нужны два объекта, и это
// видно в коде, а не подразумевается.
//
// РАЗБОР, ПОЧЕМУ ОСТАЛЬНЫЕ `thread_local` В ПРОЕКТЕ ОСТАЛИСЬ. Их три, и ни один не того же рода:
// `gns_dispatcher::active_` — трамплин для C-коллбека чужой библиотеки (у него нет пользовательского
// указателя, а значит и другого способа вернуться к объекту), выставляется и снимается вокруг одного
// `pump()`; `catalogue::detail::current_record_context` — ОБЪЕМЛЮЩАЯ ОБЛАСТЬ по RAII, ради которой
// он и заведён: протаскивать её через каждую отложенную функцию значило бы вписать её в каждую
// подпись; третий живёт в тесте. Неправильным был ровно этот случай — СКРЫТОЕ КЭШИРУЮЩЕЕ СОСТОЯНИЕ,
// у которого не названы ни владелец, ни момент смерти.
//
// СОСТОЯНИЕ glslang ПОДНИМАЕТСЯ ЛЕНИВО, при первой НАСТОЯЩЕЙ компиляции. Это не оптимизация
// конструктора, а условие того, чтобы дисковый кэш имел смысл: полностью тёплый прогон не
// конструирует компилятор ВОВСЕ и не платит те самые 90 мс.

namespace devils_engine {
namespace painter {

// Зависимость компиляции: что подставил `#include` и каким было его содержимое. Хранится в записи
// кэша, потому что ключ по одному тексту шейдера не заметил бы правку включённого файла — а это
// значит «исполняется другая программа, чем написана», то есть худший род ошибки.
struct shader_dependency {
  std::string name;
  uint64_t content_hash = 0;
};

class shader_compiler {
public:
  shader_compiler();
  ~shader_compiler() noexcept;

  shader_compiler(const shader_compiler&) = delete;
  shader_compiler& operator=(const shader_compiler&) = delete;
  shader_compiler(shader_compiler&&) noexcept;
  shader_compiler& operator=(shader_compiler&&) noexcept;

  // Куда класть готовый SPIR-V между запусками. Пусто (по умолчанию) — кэша нет вовсе: каталог, в
  // который нельзя писать, обязан вести себя как отсутствие кэша, а не как ошибка компиляции.
  void set_cache_directory(std::string path);
  const std::string& cache_directory() const noexcept;

  // Поднято ли состояние glslang. Спрашивается замерами и тестом «тёплый прогон не заводит
  // компилятор»: без этого вопроса обещание дискового кэша нечем проверить.
  bool glslang_started() const noexcept;

  // Счётчики за время жизни объекта: сколько раз ответил кэш и сколько раз пришлось компилировать.
  size_t cache_hits() const noexcept;
  size_t compilations() const noexcept;

private:
  friend class shader_crafter;

  struct state;
  std::unique_ptr<state> state_;
};

} // namespace painter
} // namespace devils_engine

#endif
