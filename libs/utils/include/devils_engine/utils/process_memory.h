#ifndef DEVILS_ENGINE_UTILS_PROCESS_MEMORY_H
#define DEVILS_ENGINE_UTILS_PROCESS_MEMORY_H

#include <cstddef>

// СКОЛЬКО ПАМЯТИ ПРОЦЕСС ЗАНЯЛ НА САМОМ ДЕЛЕ.
//
// Существует ради обещания, которое библиотеки проекта дают вслух: генератор обязан уметь назвать
// свою стоимость по памяти ДО запуска. Обещание проверяемо только одним способом — сравнить
// объявленное с занятым, — а занятое до сих пор не измерял никто: числа в отчётах это СУММА
// ОБЪЯВЛЕННОГО, и разойтись с действительностью она может как угодно.
//
// МЕРИТСЯ ПИК, А НЕ ТЕКУЩЕЕ. Текущее значение говорит, сколько занято В МОМЕНТ ВОПРОСА, а вопрос
// «влезет ли генератор в память» — про максимум за прогон: временная таблица инструмента живёт
// миллисекунды и к концу шага уже возвращена аллокатору, но пока она была, машина её держала.
//
// НОЛЬ ОЗНАЧАЕТ «НЕ ИЗМЕРЯЕТСЯ ЗДЕСЬ», а не «памяти не занято»: способ узнать пик у каждой системы
// свой, и подставлять вместо него текущее значение значило бы отвечать не на тот вопрос. Вызывающий
// обязан различать эти два случая — отчёт, напечатавший ноль как измерение, хуже отсутствующего.

namespace devils_engine {
namespace utils {

// Пик резидентной памяти процесса в байтах за всё время его жизни. 0 — величина недоступна.
size_t peak_resident_bytes() noexcept;

// Резидентная память ПРЯМО СЕЙЧАС, в байтах. 0 — величина недоступна. Нужна там, где интересен не
// максимум за прогон, а изменение между двумя точками.
size_t current_resident_bytes() noexcept;

} // namespace utils
} // namespace devils_engine

#endif
