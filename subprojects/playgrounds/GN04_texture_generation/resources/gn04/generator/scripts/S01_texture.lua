-- Тело шага texture: фоновая текстура целиком, ОДНОЙ ОЧЕРЕДЬЮ на устройстве.
--
-- Тело здесь ровно то, чем тело шага и должно быть: оно расставляет маленькое множество сайтов,
-- объявляет пять проходов и называет ГРАНИЦУ. Ни одного промежуточного значения между проходами оно
-- не читает и ни одного решения по данным не принимает — значит подграф существует как целое, и его
-- можно перенести на устройство целиком.
--
-- ГДЕ СЧИТАЕТСЯ — тоже объявление, а не догадка. `device = true` означает «эта очередь решена на
-- устройстве»; все машины берут одну ветку, а та, что исполнить её не может, отказывает громко.
-- Молча посчитать это на CPU было бы худшим исходом: под тем же зерном получился бы другой мир.
--
-- ГРАНИЦ ДВЕ, и различаются они не важностью, а тем, ГДЕ ЖИВЁТ ЧИТАТЕЛЬ:
--   `output`   — сводка: её читает хост, значит она обязана приехать обратно;
--   `resident` — видимая текстура: её читал бы пост-процесс, то есть читатель остаётся на
--                устройстве. Назвать её в `output` значило бы качать мегабайт ради того, чтобы
--                проход сборки не сочли мёртвым.
--
-- Ни одной строки GLSL здесь нет и быть не может: что считает каждый проход, решили разработчики
-- движка, и устройственные формы `voronoi_label`, `filtered_blur`, `label_colour` и `count_by`
-- написаны заранее и лежат в библиотеке рядом с их телами на CPU.

return function(step)
  local sites = step.writes.sites
  local pixels = step.writes.pixels
  local summary = step.writes.summary
  local p = step.params

  local position = sites:field("position")
  local region = pixels:field("region")
  local edge = pixels:field("edge")
  local smoothed = pixels:field("smoothed")
  local colour = pixels:field("colour")
  local counts = summary:field("count")

  local site_count = sites:count()
  -- Ширина берётся у ФОРМЫ буфера: второго источника этого числа не существует.
  local side = pixels:extent().x

  -- Детерминированная россыпь без math.random: его в окружении генератора нет намеренно.
  -- Аддитивная последовательность по золотому сечению даёт равномерное покрытие без решётки, а
  -- дрожание берётся ДВИЖКОВЫМ хешем — одна функция хеша на весь движок.
  local gx, gy = 0.7548776662, 0.5698402910
  local fx, fy = 0.5, 0.5
  for i = 0, site_count - 1 do
    fx = (fx + gx) % 1.0
    fy = (fy + gy) % 1.0
    local jx = base.prng64_normalize(base.prng64(i * 2)) - 0.5
    local jy = base.prng64_normalize(base.prng64(i * 2 + 1)) - 0.5
    position:set(i, ((fx + jx * p.spread) % 1.0) * side, 0)
    position:set(i, ((fy + jy * p.spread) % 1.0) * side, 1)
  end

  local work = {
    -- 1. ОБНУЛЕНИЕ СЧЁТЧИКОВ, и оно внутри очереди, а не снаружи. Накопитель ЧИТАЕТ то, во что
    -- пишет, поэтому очередь считает эту заливку живой работой; будь она снаружи, счётчики пришлось
    -- бы ещё и передавать на устройство.
    originator.queue.fill{ outputs = { counts }, params = { value = 0 } },

    -- 2. Разметка Вороного. Второй выход — близость к границе — необязательный: он считается ТЕМ ЖЕ
    -- обходом (у самой границы расстояния до двух ближайших сайтов равны), и объявляют его те, кому
    -- он нужен.
    originator.queue.voronoi_label{
      inputs = { position },
      outputs = { region, edge },
      params = { site_count = site_count },
    },

    -- 3. Сглаживание ЧТЕНИЕМ МЕЖДУ ЭЛЕМЕНТАМИ. Единственный проход, объявляющий свой вход
    -- фильтруемым, — и единственная причина, по которой одно поле растра становится картинкой.
    originator.queue.filtered_blur{
      inputs = { edge },
      outputs = { smoothed },
      params = { radius = p.blur_radius },
    },

    -- 4. Кайма: близость к границе превращается в затенение 0..1. Какую кривую применить, решает
    -- автор обычным remap, а не константа, спрятанная внутри инструмента.
    originator.queue.remap{
      inputs = { smoothed },
      outputs = { smoothed },
      params = { scale = 1.0 / p.border, min = 0.0, max = 1.0 },
    },

    -- 5. Видимая текстура: цвет ВЫВОДИТСЯ из номера области хешем, затенение приходит вторым входом.
    originator.queue.label_colour{
      inputs = { region, smoothed },
      outputs = { colour },
      params = { dim = p.dim },
    },

    -- 6. Сводка, и только она уезжает наружу. Апертура scatter, и в очередь она пускается ровно
    -- потому, что целочисленное накопление не зависит от порядка.
    originator.queue.count_by{
      inputs = { region },
      outputs = { counts },
    },

  }

  work.device = p.on_device ~= 0

  -- ДВЕ ГРАНИЦЫ ИЗ ОДНОГО НАБОРА ВЫЗОВОВ. Работа не меняется ни на байт — меняется только то, что
  -- объявлено уезжающим, и разница в передаче между этими двумя объявлениями и есть смысл площадки.
  if p.download_all ~= 0 then
    -- ГРАНИЦА ОСМОТРА. Смотреть на посчитанное больше неоткуда: поле, не названное здесь, на хост не
    -- приедет вовсе — устройство посчитает его и там же оставит.
    work.output = { counts, region, edge, smoothed, colour }
  else
    work.output = { counts }
    work.resident = { colour }
  end

  originator.queue(work)
end
