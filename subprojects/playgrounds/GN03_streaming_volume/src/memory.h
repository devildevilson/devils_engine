#ifndef DEVILS_ENGINE_GN03_MEMORY_H
#define DEVILS_ENGINE_GN03_MEMORY_H

#include <cstdint>
#include <span>
#include <string>
#include <unordered_map>
#include <vector>

#include "devils_engine/originator/pipeline.h"

#include "streaming.h"

// ПАМЯТЬ МИРА: то, чем мир отличается от выводимого.
//
// Мир этой площадки — функция: `f(ключ чанка, зерно)`. Поэтому у него нет ни хранилища, ни сохранения:
// выгрузили чанк — освободили память, вернулись — посчитали заново, побитово то же. Пока сущность
// выводима, она бесплатна.
//
// Память начинается там, где мир перестал быть функцией: игрок что-то сделал, и теперь чанк обязан
// вернуться ДРУГИМ. Ключевое решение — хранить не мир, а ОТЛИЧИЕ:
//
//   мир = выводимое (бесплатно, пересчитывается) + отличие (хранится, сохраняется).
//
// Отсюда три свойства, каждое из которых важнее удобства:
//
//   РАЗРЕЖЕННОСТЬ. Размер склада растёт с числом ТРОНУТЫХ сущностей, а не с числом сущностей мира.
//   Пролетел сто тысяч чанков, ничего не тронул — склад пуст.
//
//   ЭТО И ЕСТЬ СОХРАНЕНИЕ. Сохранять надо ровно склад плюс зерно: остальное — функция. Файл склада
//   и есть save-файл мира, и его размер равен тому, сколько игрок в мире НАСЛЕДИЛ.
//
//   СОЕДИНЕНИЕ — ФУНКЦИЯ. Выводимые сущности плюс склад дают видимый набор одним и тем же способом,
//   независимо от того, когда чанк загрузился и в каком порядке отличия появлялись. Это проверяется,
//   потому что иначе «вернулся — а стало иначе» ловилось бы только глазами.
//
// ИДЕНТИЧНОСТЬ здесь — (ключ чанка, номер попытки генератора), а не место в выходном массиве. Место
// зависит от того, сколько попыток до неё отказалось, поэтому подкрутка любого порога сдвинула бы все
// места, и память об одной вехе стала бы памятью о другой. Номер попытки перечисляет сам цикл
// генератора, и он от порогов не зависит.
//
// Чего здесь СОЗНАТЕЛЬНО нет: сущностей, которых в выводимом мире не было вовсе (поставленных
// игроком). Это следующий уровень — им нужна собственная идентичность, не привязанная к генератору, и
// это уже реестр, а не отличие.

namespace devils_engine::gn03 {

// Что помнит мир об одной сущности.
struct prop_delta {
  // Забрана: в мире её больше нет. Выводимая сущность при этом остаётся выводимой — просто отличие
  // говорит, что её нет, и соединение её отбрасывает.
  bool taken = false;
  // Помечена игроком. Отдельно от «забрана», потому что это разные вещи: помеченная остаётся в мире.
  bool marked = false;
  // Сколько раз с ней взаимодействовали. ЕЗДИТ ВЕРХОМ на настоящем отличии и сама записи не держит —
  // см. `empty()`.
  uint32_t touches = 0;

  // ЗАПИСЬ СУЩЕСТВУЕТ РОВНО ТОГДА, КОГДА МИР ОТЛИЧАЕТСЯ ОТ ВЫВОДИМОГО, и счётчик касаний в это
  // условие НЕ входит. Критерий именно такой, а не «с сущностью что-то происходило», и разница
  // выяснилась проверкой: сначала счётчик учитывался, и снятая пометка оставляла запись навсегда —
  // то есть игрок, потрогавший и вернувший как было тысячу вех, платил за это тысячей записей в
  // сохранении.
  //
  // Правило из этого общее: величина, от которой мир не зависит, — это СТАТИСТИКА, а не отличие, и в
  // сохранении ей места нет. Как только от числа касаний начнёт что-то зависеть (веха истёрлась,
  // источник истощился), оно станет отличием и войдёт в условие само.
  bool empty() const noexcept { return !taken && !marked; }
};

// Имя сущности: чанк плюс номер попытки генератора.
struct prop_id {
  originator::chunk_key chunk{};
  uint32_t origin = 0;

  bool operator==(const prop_id& other) const noexcept = default;
};

struct prop_id_hash {
  size_t operator()(const prop_id& id) const noexcept;
};

class world_memory {
public:
  // Отличие сущности; отсутствующее означает «мир таков, каким его посчитал генератор».
  const prop_delta* find(const prop_id& id) const noexcept;

  // Изменение отличия. Пустое отличие СТИРАЕТСЯ из склада, а не хранится нулями: иначе разреженность
  // теряется от одного «потрогал и вернул как было».
  void take(const prop_id& id);
  void mark(const prop_id& id);
  void forget(const prop_id& id);

  size_t size() const noexcept { return entries_.size(); }
  void clear() noexcept { entries_.clear(); }

  // Соединение: выводимые сущности чанка плюс склад. Возвращает, сколько сущностей осталось видимыми,
  // и заполняет `visible` парами (сущность, её отличие). ФУНКЦИЯ от двух аргументов и только от них —
  // ни времени, ни порядка загрузки здесь нет.
  struct joined_prop {
    const chunk_prop* prop = nullptr;
    prop_delta delta{};
  };
  size_t join(const originator::chunk_key& chunk, std::span<const chunk_prop> derived,
              std::vector<joined_prop>& visible) const;

  // Отличия, которым в мире НИЧЕГО НЕ СООТВЕТСТВУЕТ. Появляются, когда мир изменился под сохранением:
  // другое зерно, другие настройки генератора, другая версия правил. Такое отличие НЕ выбрасывается —
  // сущность может вернуться, — но о нём говорится вслух, потому что «половина памяти игрока больше
  // ни на что не ссылается» это то, что обязано быть видно числом.
  size_t unmatched(const originator::chunk_key& chunk, std::span<const chunk_prop> derived) const;

  // Склад на диск и с диска. Это и есть сохранение мира: всё остальное — функция от зерна.
  bool save(const std::string& path) const;
  bool load(const std::string& path);

private:
  prop_delta& entry(const prop_id& id);
  void drop_if_empty(const prop_id& id);

  std::unordered_map<prop_id, prop_delta, prop_id_hash> entries_;
};

} // namespace devils_engine::gn03

#endif
