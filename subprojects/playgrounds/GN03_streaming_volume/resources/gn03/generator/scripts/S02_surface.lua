-- Тело шага surface: поверхность нулевого уровня плотности треугольниками.
--
-- Шаг короткий, и это правильно: вся работа у инструмента, а тело шага только связывает поля и
-- объявляет то, чего движок знать не может.
--
-- Объявляется здесь одна вещь — НОСИТЕЛЬ КЛЮЧА. Инструмент пишет по чужим индексам (клетка пишет в
-- свой отрезок списка вершин), то есть апертура у него scatter, а при чанкованной генерации scatter
-- по умолчанию ОТКЛОНЯЕТСЯ: глобальную группу не заканчивает ни один чанк. Здесь группа — список
-- вершин одного прохода, и чанк заканчивает его сам, поэтому автор говорит это вслух. Молчание
-- означало бы отказ, а не разрешение, и это правильный порядок: что означает ключ, знает автор
-- пайплайна, а из одного чанка это не проверяется никак.

return function(step)
  local samples = step.reads.samples
  local vertices = step.writes.vertices
  local state = step.writes.state
  local p = step.params

  local side = p.chunk_cells + 3

  originator.marching_cubes{
    -- Позиции берутся ЛОКАЛЬНЫЕ, от начала чанка: арена хранит геометрию в координатах своего чанка,
    -- а смещение чанка относительно чанка камеры живёт в таблице на кадр. Мировые позиции остаются у
    -- ПОЛЯ (`position`), потому что мир не имеет права зависеть от наблюдателя, а геометрия — имеет
    -- право не знать, где она в мире.
    inputs = { samples:field("density"), samples:field("local") },
    outputs = { vertices:field("position"), vertices:field("normal"), state:field("vertex_count") },
    params = {
      size_x = side, size_y = side, size_z = side,
      -- Полоса перекрытия: клетки берутся только внутри неё, а её узлы нужны центральной разности
      -- нормали. Один — минимум, при котором нормаль на шве точна.
      border = 1,
      iso = p.iso,
    },
    key_support = "chunk_local",
  }
end
