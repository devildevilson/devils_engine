#ifndef DEVILS_ENGINE_GN02_VISUAL_H
#define DEVILS_ENGINE_GN02_VISUAL_H

#include <cstdint>
#include <span>
#include <string>
#include <vector>

#include <glm/vec3.hpp>

#include "devils_engine/originator/pipeline.h"

// Представление результата генерации для глаз.
//
// Отделено от Vulkan-обвязки намеренно: здесь нет ни одного графического типа, поэтому и сетку, и
// палитры можно проверить числами. Графика отвечает только на вопрос «нарисовать то, что дали».
//
// Ключевое решение: сетка НЕ совпадает с клетками генератора. Клетки лежат решёткой Фибоначчи, у
// которой нет полигонов — есть только точки и соседство. Строить по ним сферические многоугольники
// значило бы завести на площадке ещё одну геометрическую задачу (выпуклая оболочка на сфере) ради
// картинки. Вместо этого рисуется икосфера, а каждая её вершина берёт значение БЛИЖАЙШЕЙ клетки:
// это тот же ответ, который даст любой потребитель пакета, потому что другого способа спросить
// «какая клетка в этом направлении» у него тоже нет.

namespace devils_engine::gn02 {

// Вершина поверхности: направление плюс клетка, к которой она относится. Треугольники развёрнуты в
// плоский массив по три вершины — общие вершины не нужны, потому что нормаль считается из
// направления, а не усредняется по соседям.
struct surface_vertex {
  glm::vec3 direction{};
  uint32_t cell = 0;
};
static_assert(sizeof(surface_vertex) == 16);

// Клетка глазами зрителя: цвет по выбранному режиму и высота для смещения поверхности.
struct cell_visual {
  glm::vec3 colour{};
  float height = 0.0f;
};
static_assert(sizeof(cell_visual) == 16);

struct view_mode {
  std::string name;
  std::string hint;
  // С какого шага пайплайна поле осмысленно. Нужно не для запрета, а для честной подписи: при
  // просмотре по шагам поле следующего шага ещё нулевое, и молча показывать «океан везде» нельзя.
  size_t ready_after_step = 1;
  // Категориальные поля рисуются плоско (цвет треугольника от его первой вершины), непрерывные —
  // с интерполяцией. Иначе метки провинций расплываются в градиент, а рельеф становится ступенчатым.
  bool categorical = false;
};

std::span<const view_mode> view_modes() noexcept;

// Икосфера с привязкой вершин к клеткам. Подразделений `subdivisions`: 20 * 4^n треугольников.
std::vector<surface_vertex> build_surface(originator::pipeline& source, uint32_t subdivisions);

// Цвет и высота каждой клетки в выбранном режиме.
std::vector<cell_visual> build_cell_visuals(originator::pipeline& source, size_t mode, size_t cells);

} // namespace devils_engine::gn02

#endif
