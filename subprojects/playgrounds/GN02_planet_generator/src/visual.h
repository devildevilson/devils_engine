// Представление результата генерации для глаз.
//
// Отделено от Vulkan-обвязки намеренно: здесь нет ни одного графического типа, поэтому и сетку, и
// палитры можно проверить числами. Графика отвечает только на вопрос «нарисовать то, что дали».
//
// Ключевое решение: сетка НЕ совпадает с клетками генератора. Клетки лежат решёткой Фибоначчи, у
// которой нет полигонов — есть только точки и соседство. Строить по ним сферические многоугольники
// значило бы завести на площадке ещё одну геометрическую задачу (выпуклая оболочка на сфере) ради
// картинки. Вместо этого рисуется икосфера, а каждая её вершина спрашивает у решётки БЛИЖАЙШИЕ
// клетки: это тот же вопрос, который задаёт любой потребитель пакета, потому что другого способа
// спросить «какая клетка в этом направлении» у него тоже нет.
//
// ВЕРШИНА БЕРЁТ ЧЕТЫРЕ КЛЕТКИ, А НЕ ОДНУ, и это ответ на «видно решётку, а не мир». С одной
// ближайшей клеткой вершина наследует её значение целиком, поэтому у рельефа появляются ТЕРРАСЫ по
// клеткам, а у границы области — полигональная ломаная: и то и другое показывает решётку Фибоначчи,
// которой в мире нет. С четырьмя клетками и весами по расстоянию непрерывное поле становится
// непрерывным, а граница области — плавной.
//
// Дальше пути расходятся, и это два РАЗНЫХ вопроса, а не один.
//
// У непрерывного поля (высота, температура) достаточно смешать четыре клетки весами по расстоянию:
// поле непрерывно, значит и картинка непрерывна, а резкость смешивания только выбирает, насколько
// мягок переход.
//
// У поля с ОБЛАСТЯМИ смешивать нельзя: цвет метки — это её ИМЯ, а смесь двух имён не значит ничего.
// Заливка обязана быть плоской, но её ФОРМА не должна быть формой решётки. Поэтому область выбирает
// ФРАГМЕНТ, а не вершина: у пикселя есть своё направление, он сам находит ближайшую клетку и считает
// ПОКРЫТИЕ каждой области в своей окрестности ядром шире шага решётки. Ведущая область забирает
// пиксель целиком, а гладкость приходит от ширины ядра.
//
// На вершине это неразрешимо, и не по недосмотру. Одно число на вершину не может назвать область:
// разбиение дискретно, и интерполяция смешивает две разные метки. Передача пары цветов со знаковым
// полем разбивается о вершины в глубине области — у них пары нет, знак не согласован с соседями, и
// на карте появляются обведённые лоскуты внутри провинций и градиенты по треугольникам.
//
// Заливка и линия границы берутся из ОДНОГО поля, и это не экономия. Пока они считались по-разному,
// линия лежала не там, где стык цветов, и это было видно как «граница и поверхность под ней не
// совпадают по способу отображения».

namespace devils_engine::gn02 {

// Вершина поверхности: направление плюс четыре клетки с весами. Треугольники развёрнуты в плоский
// массив по три вершины — общие вершины не нужны, потому что нормаль считается из направления, а не
// усредняется по соседям.
//
// Веса упакованы в четыре байта, а не лежат четырьмя float: вершин четыре миллиона, и разница между
// 32 и 44 байтами на вершину — это 48 мегабайт видеопамяти за точность, которой глазу не видно.
struct surface_vertex {
  glm::vec3 direction{};
  uint32_t weights = 0; // четыре доли по байту, сумма равна 255
  std::array<uint32_t, 4> cells{};
};
static_assert(sizeof(surface_vertex) == 32);

// Клетка глазами зрителя: цвет по выбранному режиму, высота для смещения поверхности и НОМЕР ОБЛАСТИ,
// к которой клетка относится в этом режиме.
//
// Номер лежит здесь, а не выводится из цвета, потому что по нему рисуется граница области, а цвет для
// этого не годится: равенство цветов — это догадка о равенстве метк, а не оно само. Две области с
// близкими цветами (хеш их не запрещает) остались бы без границы между ними, и понять, почему граница
// пропала именно там, было бы нельзя.
struct cell_visual {
  glm::vec3 colour{};
  float height = 0.0f;
  float area = 0.0f;
  // Суша ли эта клетка: единица или ноль. Отдельным полем, а не знаком высоты, потому что высота в
  // записи ОБРЕЗАНА нулём (вода — ровная сфера, глубину показывает цвет, а не форма). Пока берег
  // определялся по «высота больше нуля», сушей считалась вся окрестность любой клетки суши: смесь
  // положительного с нулём положительна. Гладкая ДОЛЯ суши и её уровень 0.5 — это и есть берег как
  // кривая, а не как граница клетки.
  float land = 0.0f;
  // Запись добита до двух слов по четыре числа не ради выравнивания структуры, а ради ЧТЕНИЯ: шейдер
  // берёт её двумя vec4, и второе слово (номер области и признак суши) читается отдельно от первого —
  // при выборе области цвет не нужен вовсе, а нужен он только у победившей клетки.
  std::array<float, 2> padding{};
};
static_assert(sizeof(cell_visual) == 32);

// Геометрия клетки для ФРАГМЕНТА: направление и до восьми ближайших соседей.
//
// Нужна потому, что выбор области перенесён из вершины в пиксель, а иначе он и не работает. Одно
// число на вершину не может назвать область: разбиение на области дискретно, и любая интерполяция
// между вершинами смешивает две разные метки. Попытка передать пару цветов со знаковым полем
// разбилась ровно об это — у вершины в глубине области пары нет, её знак не согласован с соседями, и
// на карте появлялись обведённые лоскуты внутри провинций и градиенты по треугольникам.
//
// Фрагмент же может спросить у решётки напрямую: у него есть своё направление, а по нему ищется
// ближайшая клетка. Поиск идёт СПУСКОМ ПО ГРАФУ от клетки, которую назвала вершина: у ячеек Вороного
// граница выпуклая, поэтому шаг «перейти к ближайшему соседу» приводит в настоящую ближайшую клетку,
// а не в локальный минимум. Треугольник мельче клетки, значит и спуск нужен на один шаг.
//
// Соседей не больше восьми: граф — симметризованный kNN по шести соседям, у него бывает и девять, но
// дальние соседи нужны только для полноты окружения, а не для спуска.
struct cell_geometry {
  glm::vec3 direction{};
  uint32_t neighbour_count = 0;
  std::array<uint32_t, 8> neighbours{};
};
static_assert(sizeof(cell_geometry) == 48);

struct view_mode {
  std::string name;
  std::string hint;
  // С какого шага пайплайна поле осмысленно. Нужно не для запрета, а для честной подписи: при
  // просмотре по шагам поле следующего шага ещё нулевое, и молча показывать «океан везде» нельзя.
  size_t ready_after_step = 1;
  // Какой уровень названных мест соответствует этому представлению. Ноль — «названий у этого поля
  // нет». Это и есть ответ на «в зависимости от выбранного представления выбираем область»: смотрим
  // на политику — выбирается герцогство, на географию — историческая область, на рельеф — ничего, и
  // выбирать там нечего.
  enum class named { none, province, sea_zone, land_mass, continent, historical_region, ocean, duchy,
                     empire, realm, landform };
  named level = named::none;
  // Есть ли у поля ОБЛАСТИ, то есть заливается ли оно ПЛОСКО по покрытию. Ставится там, где цвет —
  // это МЕТКА: смесь двух метк не значит ничего, поэтому переход обязан быть резким, а гладкость
  // должна прийти от формы границы, а не от размазывания цвета.
  //
  // Ставится и у смысловых палитр (климат, области рельефа): класс — тоже метка. Пока их смешивали
  // «мягко», обе карты выходили бусами по клеткам, потому что степень от веса отдаёт почти всё
  // ближайшей клетке. Смешивание осталось только у настоящих чисел, и там оно линейное.
  bool areas = false;
  // Обводить ли границу области линией. ОТДЕЛЬНО от наличия областей, и это ответ на «на некоторых
  // отображениях граница не нужна вовсе».
  //
  // Правило простое: линия нужна там, где цвет — имя. У провинции и титула соседние цвета случайны,
  // хеш не обещает их различимости, и без линии нельзя сказать, где кончается одна область. У климата
  // и областей рельефа палитра СМЫСЛОВАЯ — пустыня песочная, лес зелёный, — цвет сам называет класс,
  // а чёрная линия между пустыней и степью рисовала бы резкий рубеж там, где в природе переходная
  // зона: она не помогает читать карту, а сообщает неправду о ней.
  bool outline = false;
  // Различает ли палитра сушу и воду. Если да, цвет берётся РАЗДЕЛЬНО по сторонам берега, а сторону
  // выбирает фрагмент по интерполированной доле суши: тогда берег выходит резкой линией на гладкой
  // кривой, как на картах Земли, а не лестницей по клеткам. Если нет (температура, осадки), делить
  // нечего, и деление добавило бы шов там, где поле непрерывно.
  //
  // У полей с областями берег делить не надо: там граница «вода | область» и есть граница областей,
  // и рисуется она тем же покрытием, что и все остальные. Поэтому флаг стоит ровно у одного режима —
  // у рельефа, единственного, где палитра непрерывна и всё же различает воду и сушу.
  bool coast = false;
};

// Названная область для подписи: направление её центра, её номер и размер в клетках.
//
// Размер нужен не для отчёта, а для решения «подписывать ли»: подпись мельче нескольких пикселей
// нечитаема, а сотня нечитаемых подписей — это шум, который скрывает как раз то, что подписывают.
struct labelled_area {
  glm::vec3 centre{};
  uint32_t area = 0;
  float cells = 0.0f;
};

// Области того уровня, который соответствует выбранному представлению. Пустой список — законный
// ответ: у рельефа и температуры названных мест нет.
std::vector<labelled_area> collect_labelled_areas(originator::pipeline& source, view_mode::named level);

// Поиск клетки по направлению.
//
// Тот же вопрос, который задаёт и сетка, и любой потребитель пакета: «какая клетка в этом
// направлении». У решётки Фибоначчи нет полигонов, поэтому ответ — ближайшая точка, и другого ответа
// не существует. Держится отдельным объектом, потому что строится один раз на мир, а спрашивается
// каждый кадр.
class cell_locator {
public:
  explicit cell_locator(originator::pipeline& source);
  ~cell_locator();
  cell_locator(cell_locator&&) noexcept;
  cell_locator& operator=(cell_locator&&) noexcept;

  // UINT32_MAX, если клеток нет вовсе.
  uint32_t locate(const glm::vec3& direction) const;

private:
  struct state;
  std::unique_ptr<state> state_;
};

std::span<const view_mode> view_modes() noexcept;

// Геометрия клеток для фрагментного шейдера. Строится один раз на мир: она зависит только от
// положений клеток и графа соседства, а те считаются первым шагом и дальше не меняются.
std::vector<cell_geometry> build_cell_geometry(originator::pipeline& source, size_t cells);

// Икосфера с привязкой вершин к клеткам. Подразделений `subdivisions`: 20 * 4^n треугольников.
std::vector<surface_vertex> build_surface(originator::pipeline& source, uint32_t subdivisions);

// Цвет и высота каждой клетки в выбранном режиме.
std::vector<cell_visual> build_cell_visuals(originator::pipeline& source, size_t mode, size_t cells);

} // namespace devils_engine::gn02

