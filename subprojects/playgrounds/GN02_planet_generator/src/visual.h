// Представление результата генерации для глаз.
//
// Отделено от Vulkan-обвязки намеренно: здесь нет ни одного графического типа, поэтому и сетку, и
// палитры можно проверить числами. Графика отвечает только на вопрос «нарисовать то, что дали».
//
// Ключевое решение: сетка НЕ совпадает с клетками генератора. Клетки лежат решёткой Фибоначчи, у
// которой нет полигонов — есть только точки и соседство. Строить по ним сферические многоугольники
// значило бы завести на площадке ещё одну геометрическую задачу (выпуклая оболочка на сфере) ради
// картинки. Вместо этого рисуется икосфера, а каждая её вершина спрашивает у решётки БЛИЖАЙШИЕ
// клетки: это тот же вопрос, который задаёт любой потребитель пакета, потому что другого способа
// спросить «какая клетка в этом направлении» у него тоже нет.
//
// ВЕРШИНА БЕРЁТ ЧЕТЫРЕ КЛЕТКИ, А НЕ ОДНУ, и это ответ на «видно решётку, а не мир». С одной
// ближайшей клеткой вершина наследует её значение целиком, поэтому у рельефа появляются ТЕРРАСЫ по
// клеткам, а у границы области — полигональная ломаная: и то и другое показывает решётку Фибоначчи,
// которой в мире нет. С четырьмя клетками и весами по расстоянию непрерывное поле становится
// непрерывным, а граница области — плавной.
//
// Резкость перехода задаётся ПОКАЗАТЕЛЕМ СТЕПЕНИ у весов, и он свой у каждого режима. Единица даёт
// полное сглаживание (высота, температура), большое значение — почти ближайшую клетку с мягким краем
// (провинции, титулы): категориальное поле смешивать нельзя, смесь двух случайных цветов метк даёт
// третий цвет, которого нет ни у одной области.

namespace devils_engine::gn02 {

// Вершина поверхности: направление плюс четыре клетки с весами. Треугольники развёрнуты в плоский
// массив по три вершины — общие вершины не нужны, потому что нормаль считается из направления, а не
// усредняется по соседям.
//
// Веса упакованы в четыре байта, а не лежат четырьмя float: вершин четыре миллиона, и разница между
// 32 и 44 байтами на вершину — это 48 мегабайт видеопамяти за точность, которой глазу не видно.
struct surface_vertex {
  glm::vec3 direction{};
  uint32_t weights = 0; // четыре доли по байту, сумма равна 255
  std::array<uint32_t, 4> cells{};
};
static_assert(sizeof(surface_vertex) == 32);

// Клетка глазами зрителя: цвет по выбранному режиму, высота для смещения поверхности и НОМЕР ОБЛАСТИ,
// к которой клетка относится в этом режиме.
//
// Номер лежит здесь, а не выводится из цвета, потому что по нему рисуется граница области, а цвет для
// этого не годится: равенство цветов — это догадка о равенстве метк, а не оно само. Две области с
// близкими цветами (хеш их не запрещает) остались бы без границы между ними, и понять, почему граница
// пропала именно там, было бы нельзя.
struct cell_visual {
  glm::vec3 colour{};
  float height = 0.0f;
  float area = 0.0f;
  // Близость к границе области, СГЛАЖЕННАЯ по графу соседства. Именно она рисует границу, а не
  // разность весов ближайших клеток: разность весов — это граница КЛЕТКИ, и линия по ней повторяет
  // полигональную ломаную решётки, то есть показывает решётку, а не мир. Размытие рубежа по графу
  // сглаживает саму ФОРМУ границы, а не только её край на экране.
  float border = 0.0f;
  float padding[2]{};
};
static_assert(sizeof(cell_visual) == 32);

struct view_mode {
  std::string name;
  std::string hint;
  // С какого шага пайплайна поле осмысленно. Нужно не для запрета, а для честной подписи: при
  // просмотре по шагам поле следующего шага ещё нулевое, и молча показывать «океан везде» нельзя.
  size_t ready_after_step = 1;
  // Категориальные поля рисуются плоско (цвет треугольника от его первой вершины), непрерывные —
  // с интерполяцией. Иначе метки провинций расплываются в градиент, а рельеф становится ступенчатым.
  bool categorical = false;
  // Резкость смешивания четырёх ближайших клеток. Единица — полное сглаживание, большое значение —
  // почти ближайшая клетка с мягким краем. Выводится из `categorical`, а не задаётся отдельно:
  // вопрос один и тот же, и два независимых ответа на него разъехались бы.
  float blend_sharpness() const noexcept { return categorical ? 12.0f : 1.0f; }
  // Какой уровень названных мест соответствует этому представлению. Ноль — «названий у этого поля
  // нет». Это и есть ответ на «в зависимости от выбранного представления выбираем область»: смотрим
  // на политику — выбирается герцогство, на географию — историческая область, на рельеф — ничего, и
  // выбирать там нечего.
  enum class named { none, province, sea_zone, land_mass, continent, historical_region, ocean, duchy,
                     empire, realm, landform };
  named level = named::none;
};

// Названная область для подписи: направление её центра, её номер и размер в клетках.
//
// Размер нужен не для отчёта, а для решения «подписывать ли»: подпись мельче нескольких пикселей
// нечитаема, а сотня нечитаемых подписей — это шум, который скрывает как раз то, что подписывают.
struct labelled_area {
  glm::vec3 centre{};
  uint32_t area = 0;
  float cells = 0.0f;
};

// Области того уровня, который соответствует выбранному представлению. Пустой список — законный
// ответ: у рельефа и температуры названных мест нет.
std::vector<labelled_area> collect_labelled_areas(originator::pipeline& source, view_mode::named level);

// Поиск клетки по направлению.
//
// Тот же вопрос, который задаёт и сетка, и любой потребитель пакета: «какая клетка в этом
// направлении». У решётки Фибоначчи нет полигонов, поэтому ответ — ближайшая точка, и другого ответа
// не существует. Держится отдельным объектом, потому что строится один раз на мир, а спрашивается
// каждый кадр.
class cell_locator {
public:
  explicit cell_locator(originator::pipeline& source);
  ~cell_locator();
  cell_locator(cell_locator&&) noexcept;
  cell_locator& operator=(cell_locator&&) noexcept;

  // UINT32_MAX, если клеток нет вовсе.
  uint32_t locate(const glm::vec3& direction) const;

private:
  struct state;
  std::unique_ptr<state> state_;
};

std::span<const view_mode> view_modes() noexcept;

// Икосфера с привязкой вершин к клеткам. Подразделений `subdivisions`: 20 * 4^n треугольников.
std::vector<surface_vertex> build_surface(originator::pipeline& source, uint32_t subdivisions);

// Цвет и высота каждой клетки в выбранном режиме.
std::vector<cell_visual> build_cell_visuals(originator::pipeline& source, size_t mode, size_t cells);

} // namespace devils_engine::gn02

#endif
