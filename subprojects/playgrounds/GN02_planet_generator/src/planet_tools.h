#ifndef DEVILS_ENGINE_GN02_PLANET_TOOLS_H
#define DEVILS_ENGINE_GN02_PLANET_TOOLS_H

#include "devils_engine/originator/tools.h"

// Мировые ядра GN02.
//
// Разделение с библиотекой ровно то, которое объявлено в README originator: движок не описывает мир.
// В `libs/originator` уехало то, что не знает слова «планета» — решётка на сфере, симметричный CSR
// соседства, размытие и заливка по графу, выбор разнесённых затравок, выборка по индексу. Здесь
// живёт то, что без планеты не имеет смысла: скорость плиты, взаимодействие плит на границе, поле
// ветров, перенос влаги и инсоляция.
//
// Три уровня исполнения распределены по правилу «кто чем занят»:
//   нативно  — векторная и графовая арифметика: векторное произведение, поиск наветренного соседа,
//              разложение относительной скорости на сближение и сдвиг;
//   ds       — ПРАВИЛА мира: где суша, какой климат, насколько клетка пригодна для жизни, как растёт
//              население. Их автор мира правит в конфиге, не открывая C++;
//   lua      — дирижирование шагом и маленькие множества: плиты, культуры, события, подбор уровня
//              моря бисекцией.

namespace devils_engine::gn02 {

// Регистрирует мировые инструменты в реестре площадки.
void add_planet_tools(originator::tool_registry& registry);

} // namespace devils_engine::gn02

#endif
