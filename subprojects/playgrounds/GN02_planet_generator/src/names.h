#ifndef GN02_NAMES_H
#define GN02_NAMES_H

#include <string>
#include <vector>

#include "devils_engine/originator/pipeline.h"

// Названия географических мест.
//
// ПОЧЕМУ ЭТО ЖИВЁТ ЗДЕСЬ, А НЕ В ГЕНЕРАТОРЕ. Буферы генератора числовые, и это правильно: строка в
// soa-буфере означала бы либо фиксированную длину, либо отдельную арену, а обе цены платятся ни за
// что — название полностью определено затравкой. Поэтому генератор кладёт в запись места ЗАТРАВКУ
// ИМЕНИ (name_seed) и наименующую культуру, а сборка названия из них детерминирована. В пакете
// название есть, просто в свёрнутом виде — как и всё остальное в этом генераторе.
//
// Латиница, а не кириллица: атлас шрифта площадок покрывает ASCII, и русская подпись на поверхности
// планеты просто не отрисуется. Русский остаётся в отчёте и в конфигах.

namespace devils_engine::gn02 {

// Названия по уровням. Индекс совпадает с номером области, строка 0 пуста — то же соглашение, что у
// записей областей: корзина 0 означает «области нет».
struct place_names {
  std::vector<std::string> land_masses;
  std::vector<std::string> continents;
  std::vector<std::string> historical_regions;
  std::vector<std::string> oceans;
  // Титулы. Королевства в списке НЕТ намеренно: де-юре королевство — это историческая область, и
  // титул его называется её именем. Заводить второй список тех же названий значило бы утверждать,
  // что это два разных места.
  std::vector<std::string> provinces;
  std::vector<std::string> duchies;
  std::vector<std::string> empires;
  // Державы де-факто. Ранг в названии зависит от РАЗМЕРА, как и в CK: держава на сорок графств
  // называется империей, на три — графством, и никакой отдельной записи ранга для этого не нужно.
  std::vector<std::string> realms;
};

// Два порога приходят снаружи, а не читаются из пайплайна: у собранного пайплайна значений конфига
// уже не спросить — они разошлись по параметрам шагов. Оба нужны только для ВЫБОРА СЛОВА («остров»
// против безымянного массива, «море» против «океана»), а не для самого названия.
place_names build_place_names(originator::pipeline& line, const size_t continent_min_provinces,
                              const size_t ocean_zones);

} // namespace devils_engine::gn02

#endif
