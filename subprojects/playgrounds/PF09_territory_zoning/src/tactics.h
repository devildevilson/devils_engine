#ifndef DEVILS_ENGINE_PF09_TACTICS_H
#define DEVILS_ENGINE_PF09_TACTICS_H

// Вопросы, ради которых зонирование и затевалось. Место — это не только «где я»; это ещё и «где здесь
// спрятаться», «откуда просматривается вход» и «куда развести группу». Ответы на них должны опираться на
// ТУ ЖЕ геометрию, по которой ходят: отдельный «тактический слой» разошёлся бы с игровым миром, и
// разошёлся бы молча.
//
// Всё держится на одном примитиве — ВИДИМОСТИ. Укрытие это «не видно оттуда», наблюдение — «видно всё,
// что нужно», рассредоточение — «между нами видно всё». Три разных запроса и один предикат под ними.

#include <cstdint>
#include <vector>

#include <glm/vec2.hpp>

#include "zones.h"

namespace devils_engine::pf09 {

// Видно ли из точки в точку ВНУТРИ ОДНОГО МЕСТА. Границей видимости служит само место: вышел за его
// пределы — значит между точками стена, потому что покрытие полное и снаружи места стоит соседнее место.
// Это и есть выигрыш от того, что зоны замостили поверхность: не нужен отдельный список стен.
bool visible(const zone_store& store, const zone_key place, const glm::vec2 from, const glm::vec2 to);

// Втянуть точку внутрь места. Нужна там, где точка приходит с ГРАНИЦЫ: середина проёма лежит ровно на
// ребре и по правилу пикинга принадлежит ровно одной стороне — какой именно, решает округление.
bool settle_into_place(const zone_store& store, const zone_key place, glm::vec2& point);

struct tactical_spot {
  glm::vec2 position{};
  uint32_t part = 0;
  // Какой предмет даёт это укрытие. Не отладочное поле: игре нужно знать, за чем именно человек прячется,
  // — чтобы стол можно было опрокинуть, ящик поджечь, а укрытие потерять вместе с ними.
  uint32_t blocker = 0xffffffffu;
  float score = 0.0f;   // укрытию — расстояние до угрозы; наблюдению — сколько проёмов закрыто

  bool sheltered() const noexcept { return blocker != 0xffffffffu; }
};

// Точки, из которых угроза НЕ ВИДИТ. Строятся за предметами, перекрывающими взгляд: точка отступает от
// предмета в сторону, противоположную угрозе. Возвращаются только те, что действительно не просматриваются
// — проверка та же `visible`, а не построение «должно быть за предметом».
//
// ВАЖНО: угроза задаётся точкой ВНУТРИ ТОГО ЖЕ МЕСТА. Видимость определена внутри места, поэтому угроза
// снаружи «не видит» вообще ничего, и запрос выродился бы в список предметов, молча и правдоподобно.
// Для врага, который ещё не вошёл, угрозой берут середину проёма, через который он войдёт: до этого
// момента он и не видит ничего внутри — ровно то, что говорит модель.
std::vector<tactical_spot> cover_spots(const zone_store& store, const zone_key place, const glm::vec2 threat,
                                       const uint32_t limit = 8);

// Точки, с которых просматриваются входы в место. Жадный набор: каждый следующий берётся за то, сколько
// ещё не просматриваемых проёмов он закрывает. Это и есть «рассредоточиться для наблюдения»: не «встать
// подальше друг от друга», а «вместе видеть все двери».
std::vector<tactical_spot> watch_spots(const zone_store& store, const zone_key place, const uint32_t limit = 4);

enum class order_kind : uint32_t {
  hold,    // держать место: смотреть на входы
  cover,   // укрыться от угрозы
};

struct order_assignment {
  uint32_t agent = 0;
  part_ref target{};
  glm::vec2 position{};
  bool from_cover = false;
};

// Веер приказа: ОДНО распоряжение игрока превращается в разные задачи для каждого. Игрок не расставляет
// людей по точкам — он говорит «держим этот дом», а кто где встанет, решает эта функция. Назначения
// различны по построению: два человека в одной точке — это не группа, а один человек.
std::vector<order_assignment> fan_out(const zone_store& store, const zone_key place, const order_kind kind,
                                      const glm::vec2 threat, const std::vector<glm::vec2>& agents);

} // namespace devils_engine::pf09

#endif
