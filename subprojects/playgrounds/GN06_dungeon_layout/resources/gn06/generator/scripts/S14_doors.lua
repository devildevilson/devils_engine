-- Тело шага doors: ЧТО С ЧЕМ СОЕДИНЕНО.
--
-- Дверь — ЗОНА, а не свойство ребра, и дописывается она в тот же список мест. Разница не
-- косметическая: у двери две стороны, и «заперта» — это проходимость МЕСТА, одна на обе стороны, а
-- на ребре её пришлось бы держать согласованной с двух концов (в PF09 — с четырёх).
--
-- Четыре слоя выбора держатся порознь намеренно:
--
--   ТРЕБОВАНИЕ объявленные пары видов, между которыми дверь ОБЯЗАНА быть (парадный вход в зал,
--              служебный в кухню). Открываются ПЕРВЫМИ: объявленное не должно проигрывать гонку за
--              места в пределе случайному стыку;
--   ГАРАНТИЯ  остов по графу стыков: из любой зоны можно дойти до любой. Это обещание, и если
--             правила видов его не позволяют, инструмент ОТКАЗЫВАЕТ вслух, а не открывает дверь,
--             которую автор запретил;
--   ПРАВИЛА   матрица дверей и предел числа связей у вида. Жёсткие: дверь из кухни в покои не
--             появится ни ради связности, ни ради щедрости;
--   ЩЕДРОСТЬ  лишние двери поверх остова. Они ничего не обещают, поэтому зажимаются, а не отказывают
--             — и ровно они помечаются `spare`: запирать можно только ту дверь, без которой
--             связность остаётся.
--
-- Широкий проём (коридорная лента с хребтом) связью становится всегда и двери не получает: между
-- двумя коридорами нет стены, а дверь это кусок стены.
--
-- Дверь дописывается в СПИСОК МЕСТ, и больше никуда. Прежде она вдобавок рисовалась в растре, и
-- правда о двери лежала в двух представлениях сразу; теперь растр рисует проектор из того же списка,
-- и разойтись им негде.

return function(step)
  local p = step.params
  local zones = step.writes.zones
  local links = step.writes.links
  local state = step.writes.state
  local joins = step.reads.joins

  originator.open_doors{
    inputs = { joins:field("pair"), joins:field("span"), state:field("joins"),
               zones:field("kind"), state:field("zones"),
               step.reads.door_rules:field("allowed"), step.reads.kinds:field("max_links"),
               step.reads.required_doors:field("allowed") },
    outputs = { zones:field("rect"), zones:field("kind"), links:field("edge"),
                state:field("places"), state:field("links") },
    params = { wall = p.wall, door_width = p.door_width, extra_doors = p.extra_doors, door_kind = p.door_kind },
  }
end
