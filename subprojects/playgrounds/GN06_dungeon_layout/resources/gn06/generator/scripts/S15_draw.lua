-- Тело шага draw: КАК ЭТО ВЫГЛЯДИТ.
--
-- Последний шаг, и единственный во всём генераторе, который знает про клетки. До него плана в
-- пикселях не существует: участок объявлен в мере, места нарезаны в мере, стык меряется мерой, дверь
-- поставлена в мере. Здесь объявленное ОКНО участка показывается растром объявленного размера — и
-- ничего кроме.
--
-- ВЫХОД ЭТОГО ШАГА НЕ ЧИТАЕТ НИКТО, и проверить это просто: следующих шагов нет. Отсюда и обещание,
-- которое площадка проверяет прямо, — один и тот же план в любом окне и любом масштабе остаётся тем
-- же планом.
--
-- Окно приходит значениями пайплайна, потому что окно выбирает СМОТРЯЩИЙ, а не генератор: площадка
-- кладёт туда либо весь участок, либо то, что попросили ключом.

return function(step)
  local p = step.params
  local cells = step.writes.cells
  local state = step.writes.state

  -- КОЛОННЫ ИДУТ ВТОРЫМ ВХОДОМ: сначала места, потом дырки в них. Колонна не зона — по ней не ходят,
  -- связей у неё нет, вида ей не нужно, — и на картинке она обязана выглядеть ровно тем, чем
  -- является: куском стены посреди зала.
  originator.project_zones{
    inputs = { step.reads.zones:field("rect"), state:field("places"), step.reads.zones:field("shape"),
               step.reads.columns:field("rect"), state:field("columns") },
    outputs = { cells:field("zone"), state:field("lost"), state:field("merged") },
    params = { view_x = p.view_x, view_y = p.view_y, view_w = p.view_w, view_h = p.view_h },
  }
end
