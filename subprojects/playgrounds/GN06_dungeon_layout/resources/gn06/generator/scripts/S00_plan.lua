-- Тело шага plan: КУДА ВСТАЮТ КОМНАТЫ.
--
-- Отбор с отказом: выбрать прямоугольник, проверить, не задевает ли он уже принятые с учётом зазора,
-- принять или выбросить попытку целиком. Умнее здесь намеренно ничего нет — BSP-разбиение упаковало
-- бы плотнее, но у него и вид узнаваемо «расчерченный», а отбор с отказом честно показывает, чего
-- стоит плотность: числом потраченных попыток.
--
-- ГРАНИЦЫ ПЛАНА ПРИХОДЯТ ЗНАЧЕНИЕМ, а не формой буфера, и причина простая: шаг плана растра НЕ
-- КАСАЕТСЯ — он не читает и не пишет ни одной клетки. Привязка буфера ради одной его формы означала
-- бы зависимость, которой нет. Совпадение объявленной стороны с формой растра проверяет шаг carve,
-- вслух и до вырезания.

return function(step)
  local p = step.params
  local rooms = step.writes.rooms
  local state = step.writes.state

  originator.place_rooms{
    outputs = { rooms:field("rect"), state:field("rooms"), state:field("attempts") },
    params = {
      width = p.side, height = p.side,
      min_size = p.min_room, max_size = p.max_room,
      gap = p.gap, border = p.border, attempts = p.attempts,
    },
  }
end
