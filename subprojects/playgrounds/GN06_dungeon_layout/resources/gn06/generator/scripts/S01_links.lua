-- Тело шага links: ЧТО С ЧЕМ СОЕДИНЕНО.
--
-- Здесь и живёт обещание площадки. Остов (minimum spanning tree) по построению соединяет ВСЕ
-- вершины и делает это без циклов — значит из любой комнаты есть путь в любую другую, и связей
-- ровно столько, сколько нужно. Никакое локальное правило такого не даёт: раскладка, у которой
-- законна каждая пара соседей, спокойно распадается на два отрезанных куска.
--
-- Петли добавляются ПОВЕРХ уже полного ответа и ничего не чинят: дерево коридоров водят туда и
-- обратно одной дорогой, а пара лишних связей превращает его в карту с обходными путями.
--
-- Счётчик комнат приезжает ВХОДОМ, а не числом: сколько их принял предыдущий шаг, знает только он.

return function(step)
  local p = step.params
  local links = step.writes.links
  local state = step.writes.state

  originator.link_rooms{
    inputs = { step.reads.rooms:field("rect"), state:field("rooms") },
    outputs = { links:field("pair"), state:field("links") },
    params = { extra_links = p.extra_links },
  }

  -- КОНЦЫ КОРИДОРОВ ВЫВОДЯТСЯ, а не дописываются. Связь знает номера комнат, вырезанию нужны
  -- координаты — и сложить их можно либо копией центров в список связей (два места для одной
  -- истины), либо отдельным проходом, который можно повторить. Здесь второе: `link_path` это чистая
  -- функция от плана, и апертура у него `gather` — единственная параллельная во всей постройке.
  originator.link_path{
    inputs = { links:field("pair"), step.reads.rooms:field("rect") },
    outputs = { links:field("path") },
    range = { count = state:field("links") },
  }
end
