-- Тело шага joins: ЧТО С ЧЕМ ГРАНИЧИТ.
--
-- Геометрия работает РОВНО ОДИН РАЗ — здесь, НАД ПЛАНОМ. Дальше все решения (виды, двери, маршруты,
-- проверки) принимаются по СПИСКУ стыков, а не по совпадению границ: совпадение как источник
-- связности ненадёжно, две зоны расходятся на меру, и связность начинает мигать.
--
-- Растра здесь нет, и это не мелочь: пока стыки выводились из картинки, участок не мог быть крупнее
-- изображения, а цена разбора росла вместе с числом пикселей — хотя стык есть свойство десятков
-- мест. Форма при этом не потерялась: пробег считается по крайней линии места, а не по габариту.
--
-- Стык бывает двух родов, и различие несущее: ПРЯМОЙ (зоны касаются без стены) — это уже связь,
-- широкий проём, дверь ему не нужна; ЧЕРЕЗ СТЕНУ — единственный, который вправе стать дверью,
-- потому что дверь это кусок стены.

return function(step)
  local p = step.params
  local joins = step.writes.joins
  local state = step.writes.state

  originator.zone_joins{
    inputs = { step.reads.zones:field("rect"), state:field("zones"), step.reads.zones:field("shape") },
    outputs = { joins:field("pair"), joins:field("span"), state:field("joins") },
    params = { wall = p.wall, min_span = p.min_span },
  }

  -- Каноническое соседство: то, что читают инструменты графа, и первым делом решатель ограничений.
  -- Дуги симметричны и без повторов — два стыка одной пары говорят решателю то же, что один.
  originator.zone_graph{
    inputs = { joins:field("pair"), state:field("joins"), state:field("zones") },
    outputs = { step.writes.zone_offsets:field("start"), step.writes.zone_arcs:field("zone") },
  }
end
