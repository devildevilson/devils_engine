// Семейство «шахта»: граф, который ВЫГЛЯДИТ наращённым (история выработки не моделируется).
// Один код на все варианты (`mine`, `deep_mine`...): они различаются только данными архетипа.
//
// Порядок роста, и почему он такой:
//   1. обычный вход — на стороне, обращённой к соседу по обычной связи (дорога), и лагерь сразу
//      за ним. Лагерь — знание о шахтах, а не требование задания: у шахты есть обжитое устье;
//   2. главная выработка идёт вглубь, пока контент по ней не достигнет target_depth. Семейство
//      не знает о размещениях: решатель передаёт ему только «нужна глубина D»;
//   3. боковые выработки — текстура. Если задан допуск, они растут, пока общий контент не
//      достигнет выбранной внутри допуска цели, и никогда не переходят его верхнюю границу;
//   4. тайный ход — последним. Он начинается в узле, который удовлетворяет МЕСТУ ПОРТА из
//      архетипа (где у этого вида шахт выходят тайные ходы — знание архетипа, не задания), и
//      выходит на свободную клетку кольца в окне вокруг направления на соседа. Ход не
//      ветвится, начинается скрытым проходом и беден контентом, поэтому ничьей глубины не
//      меняет — и место порта проверяется уже на окончательной форме шахты.
//
// Узлы не касаются друг друга сторонами клеток, кроме пары родитель—ребёнок, поэтому граф
// остаётся деревом. Внешнее кольцо решётки занято только входами.

namespace gn07 {

struct family_request {
  const location_input* input = nullptr;
  const archetype* arch = nullptr;
  const script_env* env = nullptr;
  uint64_t seed = 0;
  int64_t target_depth = 0;
  bool has_allowance = false;
  int64_t content_min = 0;
  int64_t content_max = 0;
};

struct family_result {
  location_graph graph;
  std::string refusal;
  int64_t branches_grown = 0;
  bool valid() const noexcept { return refusal.empty(); }
};

family_result build_mine(const family_request& request);

} // namespace gn07

