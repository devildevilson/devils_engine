#ifndef DEVILS_ENGINE_PF07_FOLIAGE_H
#define DEVILS_ENGINE_PF07_FOLIAGE_H

// Заросли среза 5: много мелких инстансов, общее ветровое поле, LOD и участие в тенях.
//
// Куст сделан геометрией, а не текстурой с прозрачностью: у площадки нет ни атласа листвы, ни
// alpha-to-coverage, а крест из непрозрачных прямоугольников читается картонкой. Несколько сужающихся
// лезвий дают силуэт растения без единой текстуры.
//
// Лезвие ДВУСТОРОННЕЕ, то есть выпускается дважды с противоположным обходом и вывернутой нормалью.
// Причина административная, а не художественная: материал сцены общий с коробками и отсекает задние
// грани, а заводить второй материал ради одного флага — значит заводить и второй шаг, и второй проход
// по всем парам группы.
//
// Меш построен в ЕДИНИЧНОЙ коробке: y от нуля у корня до единицы у верхушки. Тогда локальная высота
// вершины и есть доля высоты растения, а ветру именно она и нужна — без неё пришлось бы делить на
// масштаб инстанса прямо в шейдере.

#include <cstdint>
#include <vector>

#include "fixture.h"

namespace devils_engine::pf07 {

// Полный куст и упрощённый. Разница только в числе лезвий: силуэт вдали всё равно не разобрать, а
// вершин уходит вдвое меньше.
std::vector<scene_vertex> make_shrub(uint32_t blade_count);

constexpr uint32_t shrub_blades_near = 5;
constexpr uint32_t shrub_blades_far = 2;

// Куст в мире. Хранится отдельно от `scene_instance`, потому что сортировка по дальности идёт каждый
// раз заново, а инстанс собирается уже из отсортированного.
struct shrub {
  float x = 0.0f;
  float y = 0.0f;
  float z = 0.0f;
  float width = 1.0f;
  float height = 1.0f;
  float yaw = 0.0f;
  float phase = 0.0f;
  glm::vec3 albedo{0.3f, 0.4f, 0.2f};
};

// Детерминированная посадка по долине. Плотность падает со склоном и высотой: на гребнях голо, на дне
// густо — иначе заросли выглядят наклеенными поверх рельефа, а не выросшими из него.
std::vector<shrub> scatter_shrubs(uint32_t target_count);

} // namespace devils_engine::pf07

#endif
