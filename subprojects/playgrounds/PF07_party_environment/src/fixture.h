#ifndef DEVILS_ENGINE_PF07_FIXTURE_H
#define DEVILS_ENGINE_PF07_FIXTURE_H

// Опорная геометрия среза 4. Её задача — не ландшафт, а КАСТЕРЫ: тени двух светил нечем проверять,
// пока в сцене нет ни одного предмета. Настоящая долина с зарослями приходит срезом 5, и эта фикстура
// тогда уступит ей место, поэтому она сознательно примитивна — оси-выровненные коробки одного меша.
//
// Состав выбран под измеримость, а не под красоту. Вертикальные столбы дают самое наглядное
// расхождение двух теней: при разделении светил в 13.97° столб высотой 4 м разносит концы теней на
// 0.56 м с высоты 60° и на 5.5 м с высоты 10°. Низкие плиты нужны как ПРИЁМНИКИ — тень, упавшая на
// другой предмет, ловит ошибки каскадов, которых плоская земля не показывает.

#include <cstdint>
#include <vector>

#include <glm/vec3.hpp>
#include <glm/vec4.hpp>

namespace devils_engine::pf07 {

// Вершина меша: положение и нормаль. Меш ровно один — единичный куб, всё остальное делает инстанс.
struct scene_vertex {
  float px, py, pz;
  float nx, ny, nz;
};

// Инстанс: центр и половинные размеры в МЕТРАХ плюс альбедо. Масштаб по осям, поэтому нормаль грани
// остаётся точной без обратной транспонированной матрицы.
struct scene_instance {
  glm::vec4 position_material;
  glm::vec4 half_extent_roughness;
  glm::vec4 albedo_unused;
};

// Плотность диска. Кольца геометрической прогрессией, поэтому у камеры они густые, а к горизонту
// разрежаются; на пяти километрах соседние кольца расходятся на километр, и погрешность силуэта от
// этого равна сантиметру — доли пикселя.
constexpr uint32_t ground_ring_count = 64;
constexpr uint32_t ground_segment_count = 128;

std::vector<scene_vertex> make_unit_cube();
std::vector<scene_instance> make_fixture_instances();

// Самый высокий предмет фикстуры. Нужен каскадам: запас вдоль луча света считается от него.
double fixture_caster_height(const std::vector<scene_instance>& instances);

// Земля как ГЕОМЕТРИЯ, а не как ветка в шейдере неба.
//
// Раньше поверхность планеты считалась аналитически прямо во фрагментном шейдере неба. Физически это
// было верно, но стоило непозволительно дорого: код освещения и теней, лежащий в том же шейдере,
// поднимал расход регистров, и надбавку платил даже кадр, где земли не видно вовсе — 4.9 против 6.9 мс
// при взгляде в зенит. Диск освобождает шейдер неба целиком, а срезу 5 всё равно предстоит заменить
// эту землю ландшафтом, и заменять геометрию геометрией куда проще, чем геометрией ветку шейдера.
//
// Кривизна ЗАПЕЧЕНА в вершины: без неё плоскость уходит в бесконечность и горизонта не существует.
// С запечённой кривизной поверхность отходит вниз на 2.0 м к пяти километрам, ровно скрывая себя от
// глаза на высоте двух метров — горизонт появляется сам, из геометрии, а не из формулы.
std::vector<scene_vertex> make_ground_disc(double radius_m, double planet_radius_m, uint32_t rings,
                                           uint32_t segments);
scene_instance make_ground_instance(double centre_x, double centre_z, const glm::vec3& albedo);

} // namespace devils_engine::pf07

#endif
