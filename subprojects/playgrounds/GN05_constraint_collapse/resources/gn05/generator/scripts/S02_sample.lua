-- Тело шага sample: ОБРАЗЕЦ, с которого снимаются правила.
--
-- Это единственный шаг площадки, который ничего не решает: он рисует. Смысл обучения в том, что автор
-- не пишет таблицу запретов вовсе — он показывает, КАК ДОЛЖНО БЫТЬ, а правила снимаются с картинки.
--
-- ОБУЧЕНИЕ ВОСПРОИЗВОДИТ И ОГОВОРКИ РИСУНКА, и это здесь поймано на живом примере. Первый вариант
-- этого образца качал берег по УГЛУ (`coast(angle)`), и у самого центра, где угол между соседними
-- клетками меняется быстро, ступень перепрыгивала через одну: на картинке в паре мест вода касалась
-- травы. Правила это добросовестно вынесли, и в результате вода касалась травы тоже — проверка
-- площадки поймала не решатель, а РИСУНОК.
--
-- Поэтому колебание берега — функция ПОЛОЖЕНИЯ, а не угла, и амплитуда выбрана так, чтобы у соседних
-- по стороне клеток высота отличалась меньше, чем на ширину полосы: `|Δрасстояние| <= 1` плюс
-- `|Δволна| <= 3/7 + 0` даёт меньше 1.43 при ширине полосы 2. Отсюда лесенка на рисунке соблюдена ПО
-- ПОСТРОЕНИЮ, а не по внимательности, и снятые с него правила её наследуют.

return function(step)
  local p = step.params
  local sample = step.writes.sample
  local tile = sample:field("tile")

  local side = sample:extent().x
  local half = side / 2
  local count = math.tointeger(p.tile_count) or math.floor(p.tile_count)
  if count ~= 7 then
    error(string.format("sample: the drawing knows the seven-step ladder by name and the config declares %d tiles",
                        count))
  end

  -- Ширина полосы в клетках. Она и есть то число, с которым сравнивается шаг высоты: полоса уже
  -- шага означала бы перепрыгнутую ступень.
  local band = 2.0
  local shore = half * 0.62

  for y = 0, side - 1 do
    for x = 0, side - 1 do
      local dx = (x + 0.5) - half
      local dy = (y + 0.5) - half
      local distance = math.sqrt(dx * dx + dy * dy)

      -- Волна по положению: берег перестаёт быть окружностью, а высота остаётся почти липшицевой.
      local height = distance + 3.0 * math.sin(x / 7.0) + 3.0 * math.sin(y / 6.0)
      local level = math.floor((height - shore) / band)

      -- Ступень: 2 это песок, выше воды, ниже суши. Зажим с обоих концов монотонен, поэтому лесенка
      -- сохраняется и на краях.
      local value = math.max(0, math.min(count - 1, 2 - level))
      tile:set(y * side + x, value)
    end
  end
end
