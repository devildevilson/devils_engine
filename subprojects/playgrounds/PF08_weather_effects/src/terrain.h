#ifndef DEVILS_ENGINE_PF08_TERRAIN_H
#define DEVILS_ENGINE_PF08_TERRAIN_H

// Опорная долина среза 5.
//
// Ландшафт здесь СОЗНАТЕЛЬНО примитивен: его задача — быть достаточным набором теневых кастеров и
// приёмников и местом, куда садятся заросли, а не проверкой terrain pipeline. Никаких клипмапов, LOD
// рельефа и потоковой подгрузки: один статический участок у начала координат.
//
// Ключевое решение — участок СТАТИЧЕН, а не следует за камерой. Следующий за камерой рельеф обязан
// считать высоту от МИРОВЫХ координат в вершинном шейдере, иначе он поедет вместе с наблюдателем; а
// это тянет за собой общий код для CPU и GLSL, потому что заросли надо сажать на ту же поверхность.
// Статический участок снимает вопрос целиком: высота считается один раз на CPU, и она же расставляет
// растительность. Долина — это МЕСТО, а не свойство всего мира.
//
// Ровная земля до горизонта остаётся отдельным диском под участком (см. `make_ground_disc`): участок
// к своему краю выходит в ноль и ложится на диск заподлицо.

#include <cstdint>
#include <vector>

#include "fixture.h"

namespace devils_engine::pf08 {

// Полусторона участка и шаг сетки в метрах.
constexpr double valley_half_size = 200.0;
constexpr double valley_cell = 3.0;
// Радиус, за которым рельеф уходит в ноль. Заметно меньше полустороны: край участка обязан быть
// плоским, иначе на стыке с диском появится ступенька.
constexpr double valley_fade_start = 130.0;
constexpr double valley_fade_end = 175.0;

// Высота долины в точке мира. Единственное описание рельефа: по нему строится и меш, и посадка
// зарослей, и подошвы опорных предметов.
double valley_height(double x, double z);
// Нормаль поверхности там же, из аналитического градиента.
glm::vec3 valley_normal(double x, double z);

std::vector<scene_vertex> make_valley_patch();

} // namespace devils_engine::pf08

#endif
